#!/usr/bin/env node
// Generate dat/Ran-strt.lua's fixed map and placement tables without trimming
// spaces or transparent cells. Runtime descriptor order remains in quest_levels.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Ran-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/ran_strt_level_data.js');

export function extractRanStrtData(source) {
    const match = source.match(/des\.map\(\{ halign = "left", valign = "center", map = \[\[\n([\s\S]*?)\n\]\] \}\)/u);
    if (!match) throw new SyntaxError('Ran-strt.lua has no aligned des.map block');
    const map = match[1].split('\n');
    if (map.length !== 21 || map.some(row => row.length !== 41))
        throw new SyntaxError('Ran-strt.lua map is not 21 rows of 41 columns');
    const hunters = [...source.matchAll(/des\.monster\("hunter", (\d+), (\d+)\)/gu)]
        .map(m => [Number(m[1]), Number(m[2])]);
    const centaurs = [...source.matchAll(/des\.monster\(\{ id = "forest centaur", x=(\d+), y=(\d+), peaceful=0 \}\)/gu)]
        .map(m => [Number(m[1]), Number(m[2])]);
    if (hunters.length !== 8 || centaurs.length !== 18)
        throw new SyntaxError('Ran-strt.lua fixed monster placement counts changed');
    return {map, hunters, centaurs};
}

export function renderRanStrtData({map, hunters, centaurs}) {
    return '// Generated by scripts/generate-ran-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Ran-strt.lua. Do not edit by hand.\n\n'
        + `export const RAN_STRT_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const RAN_STRT_HUNTERS = Object.freeze(${JSON.stringify(hunters, null, 4)}.map(Object.freeze));\n\n`
        + `export const RAN_STRT_FOREST_CENTAURS = Object.freeze(${JSON.stringify(centaurs, null, 4)}.map(Object.freeze));\n`;
}

async function main() {
    const rendered = renderRanStrtData(extractRanStrtData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/ran_strt_level_data.js is stale; run node scripts/generate-ran-strt-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
