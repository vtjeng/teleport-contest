#!/usr/bin/env node

// Project the static in-game help files into browser-safe line arrays.
// pager.c's display-file wrappers cannot read dat/ at runtime in this port.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'help_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';
const BUFSZ = 256;
const HELP_FILENAMES = Object.freeze([
    'help',
    'hh',
    'history',
    'opthelp',
    'optmenu',
    'usagehlp',
    'license',
]);

function expandTabs(value) {
    let result = '';
    let column = 0;
    for (const character of value) {
        if (character === '\t') {
            do {
                result += ' ';
                column += 1;
            } while (column % 8);
        } else {
            result += character;
            column += 1;
        }
        // hacklib.c tabexpand() reserves the final BUFSZ byte for '\0'.
        if (column >= BUFSZ) return result.slice(0, BUFSZ - 1);
    }
    return result;
}

export function parseHelpTextFile(source, filename) {
    if (/[^\x00-\x7f]/u.test(source))
        throw new Error(`${filename} contains a non-ASCII byte`);
    if (source.includes('\r'))
        throw new Error(`${filename} contains a carriage return`);
    if (!source) return [];

    const lines = (source.endsWith('\n') ? source.slice(0, -1) : source)
        .split('\n');
    for (const [index, line] of lines.entries()) {
        // tty_display_file() reads with dlb_fgets(buf, BUFSZ, ...). The pinned
        // files fit in one read; reject an upstream edit which would not.
        if (Buffer.byteLength(line, 'ascii') >= BUFSZ) {
            throw new Error(
                `${filename}:${index + 1} exceeds tty_display_file's buffer`,
            );
        }
    }
    return lines.map((line) => line.includes('\t') ? expandTabs(line) : line);
}

export function buildHelpTextFiles(upstreamRoot = UPSTREAM_ROOT) {
    return Object.fromEntries(HELP_FILENAMES.map((filename) => {
        const source = readFileSync(
            join(upstreamRoot, 'dat', filename), 'utf8',
        );
        return [filename, parseHelpTextFile(source, filename)];
    }));
}

function sha256(value) {
    return createHash('sha256').update(value).digest('hex');
}

function sourceHashes(upstreamRoot = UPSTREAM_ROOT) {
    return Object.fromEntries(HELP_FILENAMES.map((filename) => [
        filename,
        sha256(readFileSync(join(upstreamRoot, 'dat', filename))),
    ]));
}

export function renderHelpTextData(files, hashes = sourceHashes()) {
    return '// Generated by scripts/generate-help-data.mjs.\n'
        + `// Source: NetHack 5.0 static help files at ${PINNED_REVISION}.\n`
        + '// Do not edit this file by hand.\n\n'
        + 'export const HELP_TEXT_FILE_HASHES = Object.freeze('
        + `${JSON.stringify(hashes, null, 4)});\n\n`
        + 'export const HELP_TEXT_FILES = Object.freeze(Object.fromEntries(\n'
        + `    Object.entries(${JSON.stringify(files, null, 4)})\n`
        + '        .map(([filename, lines]) => [filename, Object.freeze(lines)]),\n'
        + '));\n';
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION) {
        throw new Error(
            `expected NetHack source ${PINNED_REVISION}; found ${revision}`,
        );
    }
    const status = execFileSync(
        'git', [
            '-C', UPSTREAM_ROOT, 'status', '--porcelain=v1',
            '--untracked-files=no',
        ],
        { encoding: 'utf8' },
    ).trim();
    if (status)
        throw new Error('refusing to generate from modified upstream sources');
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-help-data.mjs [--check]');

    assertPinnedSource();
    const output = renderHelpTextData(buildHelpTextFiles());
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports the missing generated file.
        }
        if (existing !== output) {
            console.error(
                'js/help_data.js is stale; run '
                + 'node scripts/generate-help-data.mjs',
            );
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1]
    && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
