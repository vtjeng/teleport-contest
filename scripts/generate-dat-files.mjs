#!/usr/bin/env node

// Generate js/dat_files.js: the names of the Lua files in NetHack's dat/
// directory. The unix install copies every one of them into the playground
// (sys/unix/Makefile.top), so they are the names nhlua.c nhl_loadlua() can
// open there; any other name takes its "Error opening" arm.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'dat_files.js');

// Read the tracked tree, not the working directory, so a build product or
// stray file in dat/ cannot change the list.
export function listDatLuaFiles() {
    const names = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'ls-tree', '--name-only', 'HEAD', 'dat/'],
        { encoding: 'utf8' },
    ).split('\n').filter(Boolean).map((path) => path.slice('dat/'.length));
    return names.filter((name) => name.endsWith('.lua')).sort();
}

export function renderDatFiles(names) {
    const rows = names.map((name) => `    ${JSON.stringify(name)},`).join('\n');
    return `// Generated by scripts/generate-dat-files.mjs; do not edit.
// The Lua files of NetHack's dat/ directory, which the unix install copies
// into the playground; nhlua.c nhl_loadlua() can open only these names there.
export const DAT_LUA_FILES = new Set([
${rows}
]);
`;
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-dat-files.mjs [--check]');
    const output = renderDatFiles(listDatLuaFiles());
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports a missing generated file.
        }
        if (existing !== output) {
            console.error('js/dat_files.js is stale; run node scripts/generate-dat-files.mjs');
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
