#!/usr/bin/env node

// Generate cfgfiles.c config_line_stmt[] for the recorder build. The table is
// conditional on the build configuration: USER_SOUNDS adds two player rows,
// SYSCF adds rows a player's rc must skip, and SFCTOOL removes the player rows.
// Preprocessing cfgfiles.c with the recorder's headers makes those decisions in
// C before this script reads the initializer.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync }
    from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const UPSTREAM_INCLUDE = join(UPSTREAM_ROOT, 'include');
const UPSTREAM_UNIX = join(UPSTREAM_ROOT, 'sys', 'unix');
const CFGFILES_C = join(UPSTREAM_ROOT, 'src', 'cfgfiles.c');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'config_statement_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';

// makedefs creates these headers during a build. Neither contributes a macro
// that selects a config_line_stmt[] row.
const GENERATED_HEADERS = Object.freeze(['nhlua.h', 'date.h']);

function splitFields(body) {
    const fields = [];
    let depth = 0;
    let quoted = false;
    let start = 0;
    for (let index = 0; index < body.length; ++index) {
        const ch = body[index];
        if (quoted) {
            if (ch === '\\') ++index;
            else if (ch === '"') quoted = false;
            continue;
        }
        if (ch === '"') quoted = true;
        else if (ch === '(' || ch === '[' || ch === '{') ++depth;
        else if (ch === ')' || ch === ']' || ch === '}') --depth;
        else if (ch === ',' && depth === 0) {
            fields.push(body.slice(start, index).trim());
            start = index + 1;
        }
    }
    fields.push(body.slice(start).trim());
    return fields;
}

function parseStringLiteral(field) {
    const match = field.match(/^"([A-Za-z_]+)"$/u);
    if (!match) throw new Error(`unexpected statement name: ${field}`);
    return match[1].toLowerCase();
}

function parseInteger(field, what) {
    if (!/^[0-9]+$/u.test(field))
        throw new Error(`unexpected ${what}: ${field}`);
    return Number(field);
}

function parseBoolean(field, what) {
    const match = field.match(/(?:^|\D)([01])\)?$/u);
    if (!match) throw new Error(`unexpected ${what}: ${field}`);
    return match[1] === '1';
}

function parseEntries(expanded) {
    const declaration = 'static const struct match_config_line_stmt';
    const start = expanded.indexOf(declaration);
    if (start < 0) throw new Error('config_line_stmt[] is missing');
    const initializer = expanded.indexOf('{', start);
    const end = expanded.indexOf('\n};', initializer);
    if (initializer < 0 || end < 0)
        throw new Error('config_line_stmt[] initializer is unterminated');

    const entries = [];
    const block = expanded.slice(initializer + 1, end);
    for (const match of block.matchAll(/^\s*\{\s*(.*?)\s*\},?\s*$/gmu)) {
        const fields = splitFields(match[1]);
        if (fields.length !== 5) {
            throw new Error(
                `config statement has ${fields.length} fields, expected 5: `
                + match[1],
            );
        }
        const syscnfOnly = parseBoolean(fields[2], 'syscnf_only flag');
        if (syscnfOnly) continue;
        entries.push({
            name: parseStringLiteral(fields[0]),
            minLength: parseInteger(fields[1], 'minimum match length'),
        });
    }
    if (entries.length !== 31) {
        throw new Error(
            `expected 31 player-reachable config statements; found `
            + entries.length,
        );
    }
    return entries;
}

function formatEntry({ name, minLength }) {
    return `    { name: '${name}', minLength: ${minLength} },`;
}

function formatModule(entries) {
    return `// Generated by scripts/generate-config-statements.mjs. Do not edit.
// Source: NetHack 5.0 src/cfgfiles.c config_line_stmt[], at
// ${PINNED_REVISION}.

// Player configuration reads skip syscnf_only rows. The source build also
// selects conditional rows before this table is generated.
export const configLineStatements = Object.freeze([
${entries.map(formatEntry).join('\n')}
].map(Object.freeze));
`;
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION) {
        throw new Error(
            `expected NetHack source ${PINNED_REVISION}; found ${revision}`,
        );
    }
    const status = execFileSync(
        'git',
        ['-C', UPSTREAM_ROOT, 'status', '--porcelain=v1',
            '--untracked-files=no'],
        { encoding: 'utf8' },
    ).trim();
    if (status)
        throw new Error('Refusing to generate from modified upstream sources');
    for (const header of GENERATED_HEADERS) {
        if (existsSync(join(UPSTREAM_INCLUDE, header))) {
            throw new Error(
                `${header} now ships with the pinned source; the empty `
                + 'stand-in this script supplies would hide it',
            );
        }
    }
}

function expandCfgfiles() {
    const workDir = mkdtempSync(join(tmpdir(), 'teleport-config-export-'));
    try {
        for (const header of GENERATED_HEADERS)
            writeFileSync(join(workDir, header), '');
        return execFileSync(
            'clang',
            ['-E', '-I', workDir, '-I', UPSTREAM_INCLUDE, '-I', UPSTREAM_UNIX,
                CFGFILES_C],
            { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
        );
    } finally {
        rmSync(workDir, { recursive: true, force: true });
    }
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2)) {
        throw new Error(
            'Usage: node scripts/generate-config-statements.mjs [--check]',
        );
    }

    assertPinnedSource();
    const generatedModule = formatModule(parseEntries(expandCfgfiles()));
    if (checkOnly) {
        if (readFileSync(OUTPUT_PATH, 'utf8') !== generatedModule)
            throw new Error(`${OUTPUT_PATH} is stale; regenerate it`);
        process.stdout.write(`Verified ${OUTPUT_PATH}\n`);
    } else {
        writeFileSync(OUTPUT_PATH, generatedModule);
        process.stdout.write(`Generated ${OUTPUT_PATH}\n`);
    }
}

main();
