#!/usr/bin/env node
// Generate timeout.c's shared property table in source order.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const C_PATH = join(ROOT, 'nethack-c/upstream/src/timeout.c');
const CONST_PATH = join(ROOT, 'js/const.js');
const OUTPUT_PATH = join(ROOT, 'js/timeout_property_data.js');

function parsePropertyNames(source) {
    const table = source.match(/propertynames\[\]\s*=\s*\{([\s\S]*?)^\};/mu);
    if (!table) throw new SyntaxError('timeout.c has no propertynames[] table');
    const rows = [];
    const commentFreeTable = table[1].replace(/\/\*[\s\S]*?\*\//gu, '');
    for (const [index, rawLine] of commentFreeTable.split('\n').entries()) {
        const line = rawLine.trim();
        if (!line) continue;
        const match = line.match(/^\{\s*([A-Z][A-Z_0-9]*|0)\s*,\s*("(?:[^"\\]|\\.)*"|0)\s*\},?$/u);
        if (!match)
            throw new SyntaxError(`unsupported timeout.c property row ${index + 1}: ${rawLine}`);
        const propNum = match[1] === '0' ? 0 : match[1];
        const propName = match[2] === '0' ? null : JSON.parse(match[2]);
        rows.push({ prop_num: propNum, prop_name: propName });
    }
    if (rows.length < 2 || rows.at(-1).prop_num !== 0
        || rows.at(-1).prop_name !== null
        || rows.slice(0, -1).some(row => row.prop_num === 0 || row.prop_name === null)) {
        throw new Error('timeout.c propertynames[] must end in one null sentinel row');
    }
    const constants = readFileSync(CONST_PATH, 'utf8');
    for (const name of new Set(rows.slice(0, -1).map(row => row.prop_num))) {
        if (!new RegExp(`^export const ${name}\\b`, 'mu').test(constants))
            throw new Error(`js/const.js does not export timeout property ${name}`);
    }
    return rows;
}

function renderPropertyData(rows) {
    const names = [...new Set(rows.slice(0, -1).map(row => row.prop_num))];
    const imports = names.map(name => `    ${name},`).join('\n');
    const entries = rows.map(({ prop_num, prop_name }) => (
        `    Object.freeze({ prop_num: ${prop_num}, prop_name: ${JSON.stringify(prop_name)} }),`
    )).join('\n');
    return '// Generated by scripts/generate-timeout-property-data.mjs from\n'
        + '// nethack-c/upstream/src/timeout.c propertynames[]. Do not edit by hand.\n\n'
        + `import {\n${imports}\n} from './const.js';\n\n`
        + `export const TIMEOUT_PROPERTY_NAMES = Object.freeze([\n${entries}\n]);\n`;
}

export function generateTimeoutPropertyData(source = readFileSync(C_PATH, 'utf8')) {
    return renderPropertyData(parsePropertyNames(source));
}

function main() {
    const rendered = generateTimeoutPropertyData();
    if (process.argv.includes('--check')) {
        if (readFileSync(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/timeout_property_data.js is stale; run node scripts/generate-timeout-property-data.mjs');
    } else {
        writeFileSync(OUTPUT_PATH, rendered);
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
