#!/usr/bin/env node

// Generate the fixed shirt, apron, Hawaiian-shirt, and candy-wrapper tables
// used by read.c text helpers. Keep their order and wording tied to C.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'src', 'read.c');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'read_text_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';
const TABLE_NAMES = [
    'shirt_msgs', 'hawaiian_motifs', 'hawaiian_bgs', 'apron_msgs',
    'candy_wrappers',
];
const EXPORT_NAMES = Object.freeze({
    shirt_msgs: 'SHIRT_MESSAGES',
    hawaiian_motifs: 'HAWAIIAN_MOTIFS',
    hawaiian_bgs: 'HAWAIIAN_BACKGROUNDS',
    apron_msgs: 'APRON_MESSAGES',
    candy_wrappers: 'CANDY_WRAPPERS',
});

function stripCComments(source) {
    let result = '';
    let inString = false;
    for (let index = 0; index < source.length; ++index) {
        const current = source[index];
        const next = source[index + 1];
        if (inString) {
            result += current;
            if (current === '\\' && next != null) {
                result += next;
                ++index;
            } else if (current === '"') {
                inString = false;
            }
            continue;
        }
        if (current === '"') {
            inString = true;
            result += current;
            continue;
        }
        if (current === '/' && next === '*') {
            index += 2;
            while (index < source.length
                   && !(source[index] === '*' && source[index + 1] === '/')) {
                if (source[index] === '\n') result += '\n';
                ++index;
            }
            ++index;
            continue;
        }
        if (current === '/' && next === '/') {
            index += 2;
            while (index < source.length && source[index] !== '\n') ++index;
            if (index < source.length) result += '\n';
            continue;
        }
        result += current;
    }
    if (inString) throw new Error('unterminated C string in read.c');
    return result;
}

function splitInitializers(body, tableName) {
    const entries = [];
    let quote = false;
    let parens = 0;
    let start = 0;
    for (let index = 0; index < body.length; ++index) {
        const current = body[index];
        if (quote) {
            if (current === '\\') ++index;
            else if (current === '"') quote = false;
            continue;
        }
        if (current === '"') quote = true;
        else if (current === '(') ++parens;
        else if (current === ')') --parens;
        else if (current === ',' && parens === 0) {
            entries.push(body.slice(start, index));
            start = index + 1;
        }
    }
    entries.push(body.slice(start));
    return entries.filter((entry) => entry.trim()).map((entry, index) => {
        const literals = [...entry.matchAll(/"(?:\\.|[^"\\])*"/gu)]
            .map(([literal]) => JSON.parse(literal));
        const remainder = entry.replace(/"(?:\\.|[^"\\])*"/gu, '')
            .replace(/[()+\s]/gu, '');
        if (!literals.length || remainder)
            throw new Error(`unparsed ${tableName}[${index}] initializer: ${entry}`);
        return literals.join('');
    });
}

export function parseReadTextTables(source) {
    const clean = stripCComments(source);
    const tables = {};
    for (const name of TABLE_NAMES) {
        const escaped = name.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
        const body = clean.match(
            new RegExp(`(?:static\\s+)?const\\s+char\\s*\\*const\\s+${escaped}\\[\\]\\s*=\\s*\\{([\\s\\S]*?)\\};`, 'u'),
        )?.[1];
        if (!body) throw new Error(`read.c ${name}[] was not found`);
        tables[name] = splitInitializers(body, name);
    }
    const expectedLengths = {
        // These counts are the C array sizes in the pinned read.c revision.
        shirt_msgs: 70,
        hawaiian_motifs: 16,
        hawaiian_bgs: 11,
        apron_msgs: 10,
        candy_wrappers: 13,
    };
    for (const name of TABLE_NAMES) {
        if (tables[name].length !== expectedLengths[name])
            throw new Error(`${name} has ${tables[name].length} entries; expected ${expectedLengths[name]}`);
    }
    return Object.freeze(tables);
}

export function renderReadTextData(tables) {
    return '// Generated by scripts/generate-read-text-data.mjs. Do not edit.\n'
        + `// Source: NetHack 5.0 read.c at ${PINNED_REVISION}.\n\n`
        + TABLE_NAMES.map((name) => {
            const exportName = EXPORT_NAMES[name];
            return `export const ${exportName} = Object.freeze(${JSON.stringify(tables[name], null, 4)});`;
        }).join('\n\n') + '\n';
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'],
        { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION)
        throw new Error(`expected NetHack source ${PINNED_REVISION}; found ${revision}`);
    const status = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'status', '--porcelain=v1', '--untracked-files=no'],
        { encoding: 'utf8' },
    ).trim();
    if (status) throw new Error('refusing to generate from modified upstream sources');
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-read-text-data.mjs [--check]');
    assertPinnedSource();
    const output = renderReadTextData(
        parseReadTextTables(readFileSync(SOURCE_PATH, 'utf8')),
    );
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports a missing generated file.
        }
        if (existing !== output) {
            console.error('js/read_text_data.js is stale; run node scripts/generate-read-text-data.mjs');
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
    main();
