#!/usr/bin/env node

// Generate polyself.c:mbodypart() anatomy tables from the pinned C source.
// Keep the spelling, index order, and exceptional claw classes tied to C;
// polyself.js owns the branch logic that selects among these values.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'src', 'polyself.c');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'polyself_bodyparts.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';
const TABLE_NAMES = [
    'humanoid', 'jelly', 'animal', 'bird', 'horse', 'sphere',
    'fungus', 'vortex', 'snake', 'worm', 'spider', 'fish',
];

export function parseBodypartTables(source) {
    const functionStart = source.indexOf('mbodypart(struct monst *mon, int part)');
    const functionEnd = source.indexOf('\nconst char *\nbody_part(', functionStart);
    if (functionStart < 0 || functionEnd < 0)
        throw new Error('polyself.c mbodypart/body_part definitions not found');
    const body = source.slice(functionStart, functionEnd);
    const tables = {};

    for (const match of body.matchAll(
        /\*([a-z]+)_parts\[\]\s*=\s*\{([\s\S]*?)\}/g,
    )) {
        const name = match[1];
        const contents = match[2].replace(/\/\*[\s\S]*?\*\//g, '');
        const literals = [...contents.matchAll(/"(?:[^"\\]|\\.)*"/g)];
        const remainder = contents.replace(/"(?:[^"\\]|\\.)*"/g, '')
            .replace(/[\s,]/g, '');
        if (remainder)
            throw new Error(`unparsed C table syntax in ${name}_parts: ${remainder}`);
        tables[name] = literals.map(({ 0: literal }) => JSON.parse(literal));
    }

    if (TABLE_NAMES.some((name) => !tables[name])
        || Object.keys(tables).length !== TABLE_NAMES.length) {
        throw new Error('mbodypart() must define its twelve known anatomy tables');
    }
    for (const name of TABLE_NAMES) {
        // NO_PART is index 0 and STOMACH is index 18 in polyself.c:mbodypart.
        if (tables[name].length !== 19)
            throw new Error(`${name}_parts has ${tables[name].length} entries, expected 19`);
    }

    const clawMatch = body.match(
        /static\s+const\s+char\s+not_claws\[\]\s*=\s*\{([\s\S]*?)\}/,
    );
    if (!clawMatch)
        throw new Error('mbodypart() not_claws table not found');
    const clawBody = clawMatch[1].replace(/\/\*[\s\S]*?\*\//g, '');
    const clawClasses = [...clawBody.matchAll(/\b(S_[A-Z0-9_]+)\b/g)]
        .map((match) => match[1]);
    const clawRemainder = clawBody
        .replace(/\bS_[A-Z0-9_]+\b/g, '')
        .replace(/'\\0'/g, '')
        .replace(/[\s,]/g, '');
    if (clawRemainder)
        throw new Error(`unparsed C not_claws syntax: ${clawRemainder}`);
    if (!clawBody.includes("'\\0'"))
        throw new Error('mbodypart() not_claws table is missing its C terminator');

    return { tables, clawClasses };
}

export function renderBodypartTables({ tables, clawClasses }) {
    const sourceTables = TABLE_NAMES.map((name) => {
        const rows = tables[name].map((value) => `    ${JSON.stringify(value)},`)
            .join('\n');
        return `export const ${name.toUpperCase()}_PARTS = Object.freeze([\n${rows}\n]);`;
    });
    const clawImports = clawClasses.map((name) => `    ${name},`).join('\n');
    const clawRows = clawClasses.map((name) => `    ${name},`).join('\n');
    return (
        '// Generated by scripts/generate-polyself-bodyparts.mjs.\n'
        + `// Source: NetHack 5.0 polyself.c at ${PINNED_REVISION}.\n`
        + '// Do not edit this file by hand.\n\n'
        + `import {\n${clawImports}\n} from './monsters.js';\n\n`
        + sourceTables.join('\n\n') + '\n\n'
        + 'export const NOT_CLAWS = new Set([\n'
        + clawRows + '\n]);\n'
    );
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'],
        { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION)
        throw new Error(`expected NetHack source ${PINNED_REVISION}; found ${revision}`);
    const status = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'status', '--porcelain=v1', '--untracked-files=no'],
        { encoding: 'utf8' },
    ).trim();
    if (status)
        throw new Error('refusing to generate from modified upstream sources');
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-polyself-bodyparts.mjs [--check]');

    assertPinnedSource();
    const output = renderBodypartTables(
        parseBodypartTables(readFileSync(SOURCE_PATH, 'utf8')),
    );
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports the missing generated file.
        }
        if (existing !== output) {
            console.error('js/polyself_bodyparts.js is stale; run node scripts/generate-polyself-bodyparts.mjs');
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
    main();
