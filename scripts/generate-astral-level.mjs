#!/usr/bin/env node

// Generate the fixed Astral Plane map rows from the authoritative Lua source.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'astral.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'astral_level_data.js');

export function extractAstralMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('astral.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 20 || rows.some((row) => row.length !== 75))
        throw new SyntaxError('astral.lua map is not 20 rows of 75 columns');
    return rows;
}

export function renderAstralMap(rows) {
    return '// Generated by scripts/generate-astral-level.mjs from\n'
        + '// nethack-c/upstream/dat/astral.lua. Do not edit by hand.\n\n'
        + `export const ASTRAL_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderAstralMap(extractAstralMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered)
            throw new Error('js/astral_level_data.js is stale; run node scripts/generate-astral-level.mjs');
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
