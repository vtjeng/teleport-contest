#!/usr/bin/env node

// Generate coloratt.c colornames[] and colortable[], the basic aliases and
// canonical RGB catalog used by enhanced window-color parsing. Keeping every
// row in source order matters for first-match alias and RGB-name selection.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'src', 'coloratt.c');
const COLOR_HEADER_PATH = join(UPSTREAM_ROOT, 'include', 'color.h');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'color_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';

const COLOR_TYPES = Object.freeze({
    NHC: 'nh_color',
    NOC: 'no_color',
    RGBC: 'rgb_color',
});

export function extractColorNames(source, colorHeader) {
    const constants = new Map();
    for (const match of colorHeader.matchAll(
        /^#define\s+(CLR_[A-Z_]+|NO_COLOR)\s+(\d+)\b/gmu,
    )) constants.set(match[1], Number(match[2]));

    const start = source.indexOf(
        'static const struct color_names colornames[] = {',
    );
    if (start < 0) throw new Error('coloratt.c has no colornames[] initializer');
    const end = source.indexOf('\n};', start);
    if (end < 0) throw new Error('coloratt.c colornames[] is unterminated');
    const block = source.slice(start, end);
    const entries = [];
    const row = /\{\s*(?:"([^"]+)"|\(const char \*\)\s*0)\s*,\s*(CLR_[A-Z_]+|NO_COLOR)\s*\}/gu;
    for (const match of block.matchAll(row)) {
        const color = constants.get(match[2]);
        if (color === undefined)
            throw new Error(`color.h has no numeric ${match[2]} definition`);
        entries.push({ name: match[1] ?? null, color });
    }
    if (entries.length !== 27)
        throw new Error(`expected 27 color-name rows; found ${entries.length}`);
    if (entries[16].name !== null)
        throw new Error('expected colornames[] alias sentinel at row 16');
    return entries;
}

export function extractColorTable(source) {
    const start = source.indexOf('const struct nethack_color colortable[] = {');
    if (start < 0) throw new Error('coloratt.c has no colortable[] initializer');
    const end = source.indexOf('\n};', start);
    if (end < 0) throw new Error('coloratt.c colortable[] is unterminated');
    const block = source.slice(start, end);
    const entries = [];
    const row = /\{\s*(NHC|NOC|RGBC)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*"([^"]+)"\s*,\s*(0x[0-9a-f]+)\s*,\s*(0x[0-9a-f]+)\s*,\s*(0x[0-9a-f]+)\s*\}/giu;
    for (const match of block.matchAll(row)) {
        entries.push({
            type: COLOR_TYPES[match[1].toUpperCase()],
            tableIndex: Number(match[2]),
            rgbIndex: Number(match[3]),
            name: match[4],
            r: Number.parseInt(match[5], 16),
            g: Number.parseInt(match[6], 16),
            b: Number.parseInt(match[7], 16),
        });
    }
    if (entries.length !== 155) {
        throw new Error(`expected 155 color rows; found ${entries.length}`);
    }
    entries.forEach((entry, index) => {
        if (entry.tableIndex !== index) {
            throw new Error(
                `color row ${index} has table index ${entry.tableIndex}`,
            );
        }
        const expectedRgb = index < 16 ? 0 : index - 16;
        if (entry.rgbIndex !== expectedRgb) {
            throw new Error(
                `color row ${index} has RGB index ${entry.rgbIndex}, not `
                    + `${expectedRgb}`,
            );
        }
    });
    return entries;
}

export function renderColorData(names, entries) {
    const nameRows = names.map((entry) => (
        `    Object.freeze(${JSON.stringify(entry)}),`
    )).join('\n');
    const tableRows = entries.map((entry) => (
        `    Object.freeze(${JSON.stringify(entry)}),`
    )).join('\n');
    return `// Generated by scripts/generate-color-data.mjs.\n`
        + `// Source: NetHack 5.0 src/coloratt.c at ${PINNED_REVISION}.\n\n`
        + `export const COLOR_NAMES = Object.freeze([\n${nameRows}\n]);\n\n`
        + `export const COLOR_TABLE = Object.freeze([\n${tableRows}\n]);\n`;
}

function assertPinnedSource() {
    const actualRevision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], { encoding: 'utf8' },
    ).trim();
    if (actualRevision !== PINNED_REVISION) {
        throw new Error(
            `expected NetHack source ${PINNED_REVISION}; found ${actualRevision}`,
        );
    }
    const upstreamStatus = execFileSync(
        'git', [
            '-C', UPSTREAM_ROOT, 'status', '--porcelain=v1',
            '--untracked-files=no',
        ],
        { encoding: 'utf8' },
    ).trim();
    if (upstreamStatus) {
        throw new Error(
            'Refusing to generate from modified tracked upstream sources',
        );
    }
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2)) {
        throw new Error(
            'Usage: node scripts/generate-color-data.mjs [--check]',
        );
    }
    assertPinnedSource();
    const source = readFileSync(SOURCE_PATH, 'utf8');
    const output = renderColorData(
        extractColorNames(source, readFileSync(COLOR_HEADER_PATH, 'utf8')),
        extractColorTable(source),
    );
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports a missing generated file.
        }
        if (existing !== output) {
            console.error(
                'js/color_data.js is stale; run '
                    + 'node scripts/generate-color-data.mjs',
            );
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
