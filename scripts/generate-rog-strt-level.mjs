#!/usr/bin/env node
// Generate Rog-strt's fixed map and ordered descriptor tables from Lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE = path.join(ROOT, 'nethack-c/upstream/dat/Rog-strt.lua');
const OUTPUT = path.join(ROOT, 'js/rog_strt_level_data.js');

export function extractRogStrtData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u)?.[1].split('\n');
    // Lua18–38 is a full 76-column, 21-row fragment.
    if (!map || map.length !== 21 || map.some(row => row.length !== 76))
        throw new SyntaxError('Rog-strt map dimensions changed');
    const doors = [...source.matchAll(/des\.door\("([^"]+)",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, state, x, y]) => [state, Number(x), Number(y)]);
    const guards = [...source.matchAll(/des\.monster\("thug",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, x, y]) => [Number(x), Number(y)]);
    const exits = [...source.matchAll(/des\.monster\(\{ id = "([^"]+)", x=(\d+), y=(\d+), peaceful=0 \}\)/gu)]
        .map(([, id, x, y]) => ({ id, x: Number(x), y: Number(y), peaceful: 0 }));
    // Preserve all 46 door calls (including duplicate23,14), nine guards,
    // and eight fixed hostile exit monsters from Lua59–153.
    if (doors.length !== 46 || guards.length !== 9 || exits.length !== 8)
        throw new SyntaxError('Rog-strt fixed descriptor tables changed');
    return { map, doors, guards, exits };
}

export function renderRogStrtData(data) {
    let result = '// Generated by scripts/generate-rog-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Rog-strt.lua. Do not edit by hand.\n\n';
    for (const [key, name] of Object.entries({ map: 'LEVEL_MAP', doors: 'DOORS',
        guards: 'GUARDS', exits: 'EXIT_MONSTERS' }))
        result += `export const ROG_STRT_${name} = Object.freeze(${JSON.stringify(data[key], null, 4)});\n\n`;
    return result.trimEnd() + '\n';
}

async function main() {
    const rendered = renderRogStrtData(extractRogStrtData(await fs.readFile(SOURCE, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT, 'utf8') !== rendered)
            throw new Error('rog_strt_level_data.js is stale; run node scripts/generate-rog-strt-level.mjs');
    } else await fs.writeFile(OUTPUT, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
