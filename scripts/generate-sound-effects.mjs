#!/usr/bin/env node

// Generate sounds.c's se_mappings_init[] projection from include/seffects.h.
// SND_SOUNDEFFECTS_AUTOMAP expands each seffect(name) row into the matching
// sound-effect enum value and its filename basename.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'include', 'seffects.h');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'sound_effects_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';

export function parseSoundEffectBasenames(source) {
    const entries = ['']; // se_zero_invalid
    for (const match of source.matchAll(
        /^\s*seffect\(([A-Za-z0-9_]+)\),?\s*$/gmu,
    )) {
        entries.push(match[1]);
    }
    if (entries.length === 1)
        throw new Error('no seffect() entries found in include/seffects.h');
    return entries;
}

export function renderSoundEffectData(entries) {
    const rows = entries.map((entry) => `    ${JSON.stringify(entry)},`)
        .join('\n');
    return (
        '// Generated by scripts/generate-sound-effects.mjs.\n'
        + `// Source: NetHack 5.0 include/seffects.h at ${PINNED_REVISION}.\n`
        + '// Do not edit this file by hand.\n\n'
        + '// C refs: sndprocs.h sound_effect_entries; '
        + 'sounds.c se_mappings_init[].\n'
        + 'export const SOUND_EFFECT_BASE_FILENAMES = Object.freeze([\n'
        + rows + '\n'
        + ']);\n'
    );
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION) {
        throw new Error(
            `expected NetHack source ${PINNED_REVISION}; found ${revision}`,
        );
    }
    const status = execFileSync(
        'git', [
            '-C', UPSTREAM_ROOT, 'status', '--porcelain=v1',
            '--untracked-files=no',
        ],
        { encoding: 'utf8' },
    ).trim();
    if (status)
        throw new Error('refusing to generate from modified upstream sources');
}

function main() {
    const checkOnly = process.argv.length === 3
        && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2)) {
        throw new Error(
            'Usage: node scripts/generate-sound-effects.mjs [--check]',
        );
    }

    assertPinnedSource();
    const output = renderSoundEffectData(
        parseSoundEffectBasenames(readFileSync(SOURCE_PATH, 'utf8')),
    );
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports the missing generated file.
        }
        if (existing !== output) {
            console.error(
                'js/sound_effects_data.js is stale; run '
                + 'node scripts/generate-sound-effects.mjs',
            );
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1]
    && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
