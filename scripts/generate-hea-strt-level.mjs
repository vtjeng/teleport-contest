#!/usr/bin/env node
// Generate the fixed map, door and attendant tables from dat/Hea-strt.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Hea-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/hea_strt_level_data.js');
export function extractHeaStrtData(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('Hea-strt.lua has no map block');
    const map = match[1].split('\n');
    // Lua's map is twenty rows, each seventy-six columns wide.
    if (map.length !== 20 || map.some(row => row.length !== 76))
        throw new SyntaxError('Hea-strt.lua map is not 20 rows of 76 columns');
    const doors = [...source.matchAll(/des\.door\("([^"]+)",([0-9]+),([0-9]+)\)/gu)]
        .map(([, type, x, y]) => [type, Number.parseInt(x, 10), Number.parseInt(y, 10)]);
    const attendants = [...source.matchAll(/des\.monster\("attendant",\s*([0-9]+),\s*([0-9]+)\)/gu)]
        .map(([, x, y]) => [Number.parseInt(x, 10), Number.parseInt(y, 10)]);
    // Refuse to omit a changed source table instead of producing partial data.
    if (doors.length !== 12 || attendants.length !== 8)
        throw new SyntaxError('Hea-strt.lua fixed door or attendant table changed');
    return { map, doors, attendants };
}
export function renderHeaStrtData({ map, doors, attendants }) {
    return '// Generated by scripts/generate-hea-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Hea-strt.lua. Do not edit by hand.\n\n'
        + `export const HEA_STRT_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const HEA_STRT_DOORS = Object.freeze(${JSON.stringify(doors, null, 4)});\n\n`
        + `export const HEA_STRT_ATTENDANTS = Object.freeze(${JSON.stringify(attendants, null, 4)});\n`;
}
async function main() {
    const rendered = renderHeaStrtData(extractHeaStrtData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/hea_strt_level_data.js is stale; run node scripts/generate-hea-strt-level.mjs');
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
