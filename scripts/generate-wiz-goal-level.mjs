#!/usr/bin/env node
// Generate fixed Wizard Quest goal data from dat/Wiz-goal.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Wiz-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/wiz_goal_level_data.js');

function parseLuaValue(value) {
    const trimmed = value.trim();
    if (/^"(?:[^"\\]|\\.)*"$/u.test(trimmed)) return JSON.parse(trimmed);
    if (/^-?\d+$/u.test(trimmed)) return Number(trimmed);
    throw new SyntaxError(`unsupported Wiz-goal.lua descriptor value: ${trimmed}`);
}

function splitArguments(source) {
    const args = [];
    let start = 0;
    let quoted = false;
    let escaped = false;
    for (let i = 0; i < source.length; ++i) {
        const character = source[i];
        if (escaped) escaped = false;
        else if (quoted && character === '\\') escaped = true;
        else if (character === '"') quoted = !quoted;
        else if (character === ',' && !quoted) {
            args.push(source.slice(start, i));
            start = i + 1;
        }
    }
    args.push(source.slice(start));
    return args.filter(argument => argument.trim() !== '').map(parseLuaValue);
}

function parseDescriptorTable(expression, label) {
    const body = expression.trim().slice(1, -1);
    const fields = [...body.matchAll(
        /([A-Za-z_][A-Za-z_0-9]*)\s*=\s*("(?:[^"\\]|\\.)*"|-?\d+|true|false)/gu,
    )];
    let residue = body.replace(
        /([A-Za-z_][A-Za-z_0-9]*)\s*=\s*("(?:[^"\\]|\\.)*"|-?\d+|true|false)/gu,
        '',
    );
    // In this source the bare `random` table value is an undefined Lua global.
    // Its array value is nil, which leaves the array entry absent.
    residue = residue.replace(/\brandom\b/gu, '').replace(/[\s,]/gu, '');
    if (!fields.length || residue)
        throw new SyntaxError(`unsupported ${label} descriptor table: ${expression}`);
    return Object.fromEntries(fields.map(([, key, value]) => [key, parseLuaValue(value)]));
}

function parseCallArguments(source, label) {
    const expression = source.trim();
    if (!expression) return [];
    if (expression.startsWith('{') && expression.endsWith('}'))
        return [parseDescriptorTable(expression, label)];
    return splitArguments(expression);
}

export function extractWizGoalData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Wiz-goal.lua has no map');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Wiz-goal.lua map dimensions changed');

    const doors = [...source.matchAll(
        /^\s*des\.door\("(locked|closed|open|random)",\s*(\d+),\s*(\d+)\)\s*$/gmu,
    )].map(([, state, x, y]) => [state, Number(x), Number(y)]);
    if (doors.length !== 16)
        throw new SyntaxError(`Wiz-goal.lua has ${doors.length} fixed doors, expected 16`);

    const objects = [...source.matchAll(/^\s*des\.object\((.*)\)\s*$/gmu)]
        .map(([, args]) => parseCallArguments(args, 'Wiz-goal.lua object'));
    if (objects.length !== 15)
        throw new SyntaxError(`Wiz-goal.lua has ${objects.length} object calls, expected 15`);

    const monsters = [...source.matchAll(/^\s*des\.monster\((.*)\)\s*$/gmu)]
        .map(([, args]) => parseCallArguments(args, 'Wiz-goal.lua monster'));
    if (monsters.length !== 36)
        throw new SyntaxError(`Wiz-goal.lua has ${monsters.length} monster calls, expected 36`);

    const traps = [...source.matchAll(/^\s*des\.trap\(\)\s*$/gmu)].length;
    if (traps !== 6)
        throw new SyntaxError(`Wiz-goal.lua has ${traps} random traps, expected 6`);

    return { rows, doors, objects, monsters, traps };
}

export function renderWizGoalData({ rows, doors, objects, monsters, traps }) {
    return '// Generated by scripts/generate-wiz-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Wiz-goal.lua. Do not edit by hand.\n\n'
        + [
            ['WIZ_GOAL_LEVEL_MAP', rows],
            ['WIZ_GOAL_LEVEL_DOORS', doors],
            ['WIZ_GOAL_LEVEL_OBJECTS', objects],
            ['WIZ_GOAL_LEVEL_MONSTERS', monsters],
            ['WIZ_GOAL_RANDOM_TRAP_COUNT', traps],
        ].map(([name, data]) => `export const ${name} = Object.freeze(${JSON.stringify(data, null, 4)});\n`)
            .join('\n');
}

async function main() {
    const rendered = renderWizGoalData(
        extractWizGoalData(await fs.readFile(SOURCE_PATH, 'utf8')),
    );
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/wiz_goal_level_data.js is stale; run node scripts/generate-wiz-goal-level.mjs');
    } else {
        await fs.writeFile(OUTPUT_PATH, rendered);
    }
}

if (process.argv[1] === SCRIPT_PATH) await main();
