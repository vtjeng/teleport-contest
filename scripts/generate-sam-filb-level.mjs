#!/usr/bin/env node
// Generate the fixed map from the complete Sam-filb.lua program.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Sam-filb.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/sam_filb_level_data.js');

export function extractSamFilbMap(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Sam-filb.lua has no des.map block');
    const rows = map[1].split('\n');
    if (rows.length !== 16 || rows.some(row => row.length !== 60))
        throw new SyntaxError('Sam-filb.lua map is not 16 rows of 60 columns');
    return rows;
}

export function renderSamFilbMap(rows) {
    return '// Generated by scripts/generate-sam-filb-level.mjs from\n'
        + '// nethack-c/upstream/dat/Sam-filb.lua. Do not edit by hand.\n\n'
        + `export const SAM_FILB_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const output = renderSamFilbMap(extractSamFilbMap(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== output)
            throw new Error('js/sam_filb_level_data.js is stale; run node scripts/generate-sam-filb-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, output);
}
if (process.argv[1] === SCRIPT_PATH) await main();
