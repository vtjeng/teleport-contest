#!/usr/bin/env node

// Generate the fixed map rows used by js/quest_levels.js from
// dat/Cav-strt.lua.  Keep the copied map tied to the authoritative Lua
// special-level definition.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Cav-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'cav_strt_level_data.js');

export function extractCavStrtMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('Cav-strt.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 20 || rows.some((row) => row.length !== 76)) {
        throw new SyntaxError('Cav-strt.lua map is not 20 rows of 76 columns');
    }
    return rows;
}

export function renderCavStrtMap(rows) {
    return '// Generated by scripts/generate-cav-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Cav-strt.lua. Do not edit by hand.\n\n'
        + `export const CAV_STRT_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderCavStrtMap(extractCavStrtMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/cav_strt_level_data.js is stale; run '
                + 'node scripts/generate-cav-strt-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
