#!/usr/bin/env node
// Generate the exact fixed Mon-strt map from the upstream Lua program.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
export function extractMonStrtData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u)?.[1].split('\n');
    // Lua12–33: full 76-column, 20-row fragment, including trailing spaces.
    if (!map || map.length !== 20 || map.some(row => row.length !== 76))
        throw new SyntaxError('Mon-strt.lua map dimensions changed');
    return map;
}
export function renderMonStrtData(map) {
    return '// Generated by scripts/generate-mon-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Mon-strt.lua. Do not edit by hand.\n\n'
        + `export const MON_STRT_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n`;
}
async function main() {
    const output = path.join(ROOT, 'js/mon_strt_level_data.js');
    const rendered = renderMonStrtData(extractMonStrtData(await fs.readFile(
        path.join(ROOT, 'nethack-c/upstream/dat/Mon-strt.lua'), 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(output, 'utf8') !== rendered)
            throw new Error('mon_strt_level_data.js is stale');
    } else await fs.writeFile(output, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
