#!/usr/bin/env node

// Generate the fixed map rows used by js/sanctum_levels.js from
// dat/sanctum.lua. Keep the copied table tied to the authoritative Lua level
// definition.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(
    ROOT, 'nethack-c', 'upstream', 'dat', 'sanctum.lua',
);
const OUTPUT_PATH = path.join(ROOT, 'js', 'sanctum_level_data.js');

export function extractSanctumMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('sanctum.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 20 || rows.some((row) => row.length !== 76)) {
        throw new SyntaxError(
            'sanctum.lua map is not 20 rows of 76 columns',
        );
    }
    return rows;
}

export function renderSanctumMap(rows) {
    return '// Generated by scripts/generate-sanctum-level.mjs from\n'
        + '// nethack-c/upstream/dat/sanctum.lua. Do not edit by hand.\n\n'
        + `export const SANCTUM_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderSanctumMap(extractSanctumMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/sanctum_level_data.js is stale; run '
                + 'node scripts/generate-sanctum-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
