// Generate the fixed botl.c menu metadata in source order.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as constants from '../js/const.js';
const root = fileURLToPath(new URL('../', import.meta.url));
export function generateStatusFieldData() {
    const source = readFileSync(`${root}nethack-c/upstream/src/botl.c`, 'utf8');
    const fields = [];
    const header = readFileSync(`${root}nethack-c/upstream/include/botl.h`, 'utf8');
    const enums = header.slice(header.indexOf('BL_TITLE = 0'), header.indexOf('MAXBLSTATS /*'));
    const fieldIds = Object.fromEntries([...enums.matchAll(/BL_[A-Z_]+/gu)].map((m, i) => [m[0], i]));
    const block = source.slice(source.indexOf('static struct istat_s initblstats'), source.indexOf('#undef INIT_BLSTATP'));
    for (const m of block.matchAll(/INIT_BLSTAT(P?)\("([^"]+)",\s*"[^"]*",\s*(ANY_\w+),\s*\w+,\s*(BL_\w+)(?:,\s*(BL_\w+))?\)/gu)) {
        fields.push({ name: m[2], key: m[2].toLowerCase(), type: constants[m[3]], fld: fieldIds[m[5] ?? m[4]], idxmax: m[1] ? fieldIds[m[4]] : -1 });
    }
    const conditions = [];
    const cb = source.slice(source.indexOf('const struct conditions_t conditions[]'), source.indexOf('struct condtests_t condtests'));
    const opts = [...source.slice(source.indexOf('struct condtests_t condtests')).matchAll(/\{\s*(bl_\w+),\s*"([^"]+)"/gu)];
    for (const m of cb.matchAll(/\{\s*\d+,\s*(BL_MASK_\w+),\s*(bl_\w+),\s*\{\s*"([^"]+)"/gu)) {
        const option = opts.find(x => x[1] === m[2])?.[2].toLowerCase();
        conditions.push({ mask: constants[m[1]], text: m[3], option });
    }
    const aliases = [];
    const ab = source.slice(source.indexOf('static const struct condmap condition_aliases'), source.indexOf('#endif /* STATUS_HILITES */', source.indexOf('static const struct condmap condition_aliases')));
    for (const m of ab.matchAll(/\{\s*"([^"]+)",([^}]+)\}/gu)) {
        const mask = [...m[2].matchAll(/BL_MASK_\w+/gu)].reduce((v, x) => v | constants[x[0]], 0);
        aliases.push({ name: m[1], mask });
    }
    if (fields.length !== 27 || conditions.length !== 30 || aliases.length !== 6) throw new Error('botl.c metadata shape changed');
    return '// Generated by scripts/generate-status-field-data.mjs from botl.c.\n'
        + [ ['STATUS_FIELDS', fields], ['STATUS_CONDITIONS', conditions], ['STATUS_CONDITION_ALIASES', aliases] ].map(([name, rows]) => `export const ${name} = Object.freeze(${JSON.stringify(rows, null, 4)}.map(Object.freeze));\n`).join('\n');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const output = `${root}js/status_field_data.js`;
    if (process.argv.includes('--check')) {
        if (readFileSync(output, 'utf8') !== generateStatusFieldData()) throw new Error('status field metadata is stale');
    } else writeFileSync(output, generateStatusFieldData());
}
