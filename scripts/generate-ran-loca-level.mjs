#!/usr/bin/env node

// Generate Ran-loca's fixed map and ordered descriptors from the source Lua.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Ran-loca.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'ran_loca_level_data.js');

function luaScalar(token) {
    if (token.startsWith('"')) return JSON.parse(token);
    const number = Number(token);
    if (!Number.isInteger(number)) throw new SyntaxError(`Unsupported Lua value: ${token}`);
    return number;
}

export function extractRanLocaData(source) {
    const mapMatch = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\);/u);
    if (!mapMatch) throw new SyntaxError('Ran-loca.lua has no literal des.map block');
    const map = mapMatch[1].split('\n');
    if (map.length !== 20 || map.some(row => row.length !== 55)) {
        throw new SyntaxError('Ran-loca.lua map is not 20 rows of 55 columns');
    }

    const objects = [...source.matchAll(/^des\.object\(\)$/gmu)];
    if (objects.length !== 8) throw new SyntaxError('Ran-loca.lua must place eight random objects');

    const traps = [...source.matchAll(/^des\.trap\("([^"]+)"\)$/gmu)]
        .map(([, type]) => type);
    if (traps.length !== 6
        || traps.join(',') !== 'spiked pit,spiked pit,teleport,teleport,arrow,arrow') {
        throw new SyntaxError('Ran-loca.lua trap sequence changed');
    }

    const monsters = [...source.matchAll(/^des\.monster\(\{([^\n]*)\}\)$/gmu)]
        .map(([, body]) => {
            const descriptor = {};
            const fields = [...body.matchAll(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu)];
            const residue = body.replace(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu, '')
                .replace(/[\s,]/gu, '');
            if (!fields.length || residue) {
                throw new SyntaxError(`Unsupported monster descriptor: {${body}}`);
            }
            for (const [, key, token] of fields) {
                if (!['id', 'class', 'x', 'y', 'peaceful', 'asleep'].includes(key)) {
                    throw new SyntaxError(`Unsupported monster field: ${key}`);
                }
                descriptor[key] = luaScalar(token);
            }
            if (!descriptor.id && !descriptor.class) {
                throw new SyntaxError(`Monster descriptor lacks id or class: {${body}}`);
            }
            return descriptor;
        });
    if (monsters.length !== 23) {
        throw new SyntaxError(`Ran-loca.lua has ${monsters.length}, expected 23 monster descriptors`);
    }
    return { map, objectCount: objects.length, traps, monsters };
}

export function renderRanLocaData({ map, objectCount, traps, monsters }) {
    return '// Generated by scripts/generate-ran-loca-level.mjs from\n'
        + '// nethack-c/upstream/dat/Ran-loca.lua. Do not edit by hand.\n\n'
        + `export const RAN_LOCA_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const RAN_LOCA_OBJECT_COUNT = ${objectCount};\n\n`
        + `export const RAN_LOCA_TRAPS = Object.freeze(${JSON.stringify(traps, null, 4)});\n\n`
        + `export const RAN_LOCA_MONSTERS = Object.freeze(${JSON.stringify(monsters, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderRanLocaData(extractRanLocaData(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error('js/ran_loca_level_data.js is stale; run node scripts/generate-ran-loca-level.mjs');
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
