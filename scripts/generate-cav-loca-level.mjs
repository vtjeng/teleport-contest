#!/usr/bin/env node
// Generate the fixed map and monster descriptor tables from dat/Cav-loca.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Cav-loca.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/cav_loca_level_data.js');

export function extractCavLocaData(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('Cav-loca.lua has no map block');
    const map = match[1].split('\n');
    // Lua's map is twenty rows, each seventy-six columns wide.
    if (map.length !== 20 || map.some(row => row.length !== 76))
        throw new SyntaxError('Cav-loca.lua map is not 20 rows of 76 columns');
    const monsters = [...source.matchAll(/des\.monster\(\{([^}]+)\}\)/gu)].map(([, table]) => {
        const result = {};
        for (const field of table.split(',')) {
            const entry = field.trim().match(/^(\w+)\s*=\s*(?:"([^"]+)"|([0-9]+))$/u);
            if (!entry) throw new SyntaxError('Unsupported Cav-loca monster field: ' + field);
            result[entry[1]] = entry[2] ?? Number.parseInt(entry[3], 10);
        }
        return result;
    });
    // All source monsters use literal tables; refuse silently omitted forms.
    if (monsters.length !== (source.match(/des\.monster\(/gu) ?? []).length)
        throw new SyntaxError('Unsupported Cav-loca monster descriptor');
    return { map, monsters };
}
export function renderCavLocaData({ map, monsters }) {
    return '// Generated by scripts/generate-cav-loca-level.mjs from\n'
        + '// nethack-c/upstream/dat/Cav-loca.lua. Do not edit by hand.\n\n'
        + `export const CAV_LOCA_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const CAV_LOCA_MONSTERS = Object.freeze(${JSON.stringify(monsters, null, 4)});\n`;
}
async function main() {
    const rendered = renderCavLocaData(extractCavLocaData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/cav_loca_level_data.js is stale; run node scripts/generate-cav-loca-level.mjs');
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
