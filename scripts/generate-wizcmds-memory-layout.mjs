#!/usr/bin/env node
// Development-only C ABI exporter for wizcmds.c and its accounting helpers.
// The Linux recorder uses LP64; game code imports only the generated table.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = join(root, 'nethack-c/upstream');
const output = join(root, 'js/wizcmds_data.js');
const pinnedRevision = '16ff59115315917b93185d026aeefea06db9b0f4';
const actualRevision = execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (actualRevision !== pinnedRevision) throw new Error('unexpected NetHack source revision: ' + actualRevision);
const types = ['obj', 'oextra', 'monst', 'mextra', 'egd', 'epri', 'eshk',
    'emin', 'edog', 'ebones', 'wseg', 'trap', 'engr', 'damage', 'kinfo', 'cemetery'];
const aliases = ['light_source', 'timer_element', 'NhRegion', 'NhRect', 'unsigned', 'mapseen'];
if (process.argv.slice(2).some(arg => arg !== '--check'))
    throw new Error('Usage: generate-wizcmds-memory-layout.mjs [--check]');
const worm = readFileSync(join(upstream, 'src/worm.c'), 'utf8');
const wseg = worm.match(/struct wseg \{[^]*?\};/u)?.[0];
if (!wseg) throw new Error('missing source wseg declaration');
const directory = mkdtempSync(join(tmpdir(), 'teleport-memory-layout-'));
try {
    const source = '#include "hack.h"\n#include <stdio.h>\n' + wseg
        + '\nint main(void) {\n'
        + 'if(sizeof(void*) != 8 || sizeof(long) != 8) return 1;\n'
        + types.map(name => `printf("${name}=%zu\\n", sizeof(struct ${name}));`).join('\n') + '\n'
        + aliases.map(name => `printf("${name}=%zu\\n", sizeof(${name}));`).join('\n')
        + '\nreturn 0; }\n';
    writeFileSync(join(directory, 'layout.c'), source);
    execFileSync('clang', ['-std=c99', '-DCROSSCOMPILE',
        '-I' + join(upstream, 'include'), '-I' + join(upstream, 'sys/unix'),
        join(directory, 'layout.c'), '-o', join(directory, 'layout')]);
    const layout = Object.fromEntries(execFileSync(join(directory, 'layout'), { encoding: 'utf8' })
        .trim().split('\n').map(line => { const [name, value] = line.split('='); return [name, Number(value)]; }));
    const text = '// Generated by scripts/generate-wizcmds-memory-layout.mjs.\n'
        + '// C refs: NetHack ' + pinnedRevision + '; headers and worm.c struct wseg; LP64 ABI.\n'
        + 'export const memoryLayout = Object.freeze(' + JSON.stringify(layout, null, 4) + ');\n';
    if (process.argv.includes('--check')) {
        if (readFileSync(output, 'utf8') !== text) throw new Error('memory layout table differs from pinned source');
    } else writeFileSync(output, text);
} finally { rmSync(directory, { recursive: true, force: true }); }
