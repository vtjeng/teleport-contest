#!/usr/bin/env node
// Generate the complete fixed map from dat/Rog-loca.lua, preserving spaces.
import {promises as fs} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const SCRIPT_PATH=fileURLToPath(import.meta.url);
const ROOT=path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH=path.join(ROOT,'nethack-c/upstream/dat/Rog-loca.lua');
const OUTPUT_PATH=path.join(ROOT,'js/rog_loca_level_data.js');

export function extractRogLocaMap(source) {
    const match=source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if(!match) throw new SyntaxError('Rog-loca.lua has no des.map block');
    const rows=match[1].split('\n');
    if(rows.length!==21||rows.some(row=>row.length!==76))
        throw new SyntaxError('Rog-loca.lua map is not 21 rows of 76 columns');
    return rows;
}
export function renderRogLocaMap(rows) {
    return '// Generated by scripts/generate-rog-loca-level.mjs from\n'
        +'// nethack-c/upstream/dat/Rog-loca.lua. Do not edit by hand.\n\n'
        +`export const ROG_LOCA_LEVEL_MAP = Object.freeze(${JSON.stringify(rows,null,4)});\n`;
}
async function main() {
    const rendered=renderRogLocaMap(extractRogLocaMap(await fs.readFile(SOURCE_PATH,'utf8')));
    if(process.argv.includes('--check')) {
        if(await fs.readFile(OUTPUT_PATH,'utf8')!==rendered)
            throw new Error('js/rog_loca_level_data.js is stale; run node scripts/generate-rog-loca-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH,rendered);
}
if(process.argv[1]===SCRIPT_PATH) await main();
