#!/usr/bin/env node
// Generate fixed map and descriptor tables from dat/Tou-goal.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Tou-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/tou_goal_level_data.js');

function parseLuaValue(value) {
    const trimmed = value.trim();
    if (/^"(?:[^"\\]|\\.)*"$/u.test(trimmed))
        return JSON.parse(trimmed);
    if (/^-?\d+$/u.test(trimmed)) return Number(trimmed);
    throw new SyntaxError(`unsupported Tou-goal.lua descriptor value: ${trimmed}`);
}

function splitArguments(source) {
    const args = [];
    let start = 0;
    let quoted = false;
    let escaped = false;
    for (let i = 0; i < source.length; ++i) {
        const character = source[i];
        if (escaped) {
            escaped = false;
        } else if (quoted && character === '\\') {
            escaped = true;
        } else if (character === '"') {
            quoted = !quoted;
        } else if (character === ',' && !quoted) {
            args.push(source.slice(start, i));
            start = i + 1;
        }
    }
    args.push(source.slice(start));
    return args.filter(argument => argument.trim() !== '').map(parseLuaValue);
}

function parseMonsterCall(source) {
    const expression = source.trim();
    if (expression.startsWith('{') && expression.endsWith('}')) {
        const fieldsSource = expression.slice(1, -1);
        const fields = [...fieldsSource.matchAll(
            /([A-Za-z_][A-Za-z_0-9]*)\s*=\s*("(?:[^"\\]|\\.)*"|-?\d+)/gu,
        )];
        const residue = fieldsSource.replace(
            /([A-Za-z_][A-Za-z_0-9]*)\s*=\s*("(?:[^"\\]|\\.)*"|-?\d+)/gu,
            '',
        ).replace(/[\s,]/gu, '');
        if (!fields.length || residue)
            throw new SyntaxError(`unsupported Tou-goal.lua monster table: ${expression}`);
        return [Object.fromEntries(fields.map(([, key, value]) => [key, parseLuaValue(value)]))];
    }
    return splitArguments(expression);
}

export function extractTouGoalData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Tou-goal.lua has no map');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Tou-goal.lua map dimensions changed');

    const doors = [...source.matchAll(
        /^\s*des\.door\("(locked|closed|open|random)",\s*(\d+),\s*(\d+)\)\s*$/gmu,
    )].map(([, state, x, y]) => [state, Number(x), Number(y)]);
    if (doors.length !== 27)
        throw new SyntaxError(`Tou-goal.lua has ${doors.length} fixed doors, expected 27`);

    const monsters = [...source.matchAll(/^\s*des\.monster\((.*)\)\s*$/gmu)]
        .map(([, args]) => parseMonsterCall(args));
    if (monsters.length !== 38)
        throw new SyntaxError(`Tou-goal.lua has ${monsters.length} fixed monster calls, expected 38`);

    return { rows, doors, monsters };
}

export function renderTouGoalData({ rows, doors, monsters }) {
    return '// Generated by scripts/generate-tou-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Tou-goal.lua. Do not edit by hand.\n\n'
        + [
            ['TOU_GOAL_LEVEL_MAP', rows],
            ['TOU_GOAL_LEVEL_DOORS', doors],
            ['TOU_GOAL_LEVEL_MONSTERS', monsters],
        ].map(([name, data]) => `export const ${name} = Object.freeze(${JSON.stringify(data, null, 4)});\n`)
            .join('\n');
}

async function main() {
    const rendered = renderTouGoalData(
        extractTouGoalData(await fs.readFile(SOURCE_PATH, 'utf8')),
    );
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/tou_goal_level_data.js is stale; run node scripts/generate-tou-goal-level.mjs');
    } else {
        await fs.writeFile(OUTPUT_PATH, rendered);
    }
}

if (process.argv[1] === SCRIPT_PATH) await main();
