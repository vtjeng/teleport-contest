#!/usr/bin/env node

// Generate trap.c trapname()'s fixed hallucinated-name table.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sourcePath = new URL('../nethack-c/upstream/src/trap.c', import.meta.url);
const outputPath = new URL('../js/trap_names_data.js', import.meta.url);

export function generateTrapNames(source = readFileSync(sourcePath, 'utf8')) {
    const table = source.match(/halu_trapnames\[\]\s*=\s*\{([\s\S]*?)\};/u)?.[1];
    if (!table) throw new Error('trap.c halu_trapnames[] was not found');
    const entries = [...table.replace(/\/\*[\s\S]*?\*\//gu, '')
        .matchAll(/"(?:[^"\\]|\\.)*"/gu)].map(([value]) => JSON.parse(value));
    if (!entries.length) throw new Error('trap.c halu_trapnames[] was empty');
    return '// Generated by scripts/generate-trap-names.mjs. Do not edit.\n'
        + '// C ref: trap.c trapname(), halu_trapnames[].\n'
        + `export const halu_trapnames = Object.freeze(${JSON.stringify(entries, null, 4)});\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const output = generateTrapNames();
    if (process.argv.length === 3 && process.argv[2] === '--check') {
        if (readFileSync(outputPath, 'utf8') !== output)
            throw new Error('js/trap_names_data.js is stale; run node scripts/generate-trap-names.mjs');
    } else if (process.argv.length === 2) {
        writeFileSync(outputPath, output);
    } else {
        throw new Error('Usage: node scripts/generate-trap-names.mjs [--check]');
    }
}
