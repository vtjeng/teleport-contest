#!/usr/bin/env node
// Generate the complete Tourist locate map and fixed doors from Tou-loca.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Tou-loca.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/tou_loca_level_data.js');

export function extractTouLocaData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Tou-loca.lua has no map');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Tou-loca.lua map dimensions changed');
    const doors = [...source.matchAll(/des\.door\("(closed|locked)",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, state, x, y]) => [state, Number(x), Number(y)]);
    if (doors.length !== 35)
        throw new SyntaxError('Tou-loca.lua fixed door count changed');
    return { rows, doors };
}

export function renderTouLocaData({ rows, doors }) {
    return '// Generated by scripts/generate-tou-loca-level.mjs from\n'
        + '// nethack-c/upstream/dat/Tou-loca.lua. Do not edit by hand.\n\n'
        + [['TOU_LOCA_LEVEL_MAP', rows], ['TOU_LOCA_DOORS', doors]]
            .map(([name, data]) => `export const ${name} = Object.freeze(${JSON.stringify(data, null, 4)});\n`)
            .join('\n');
}

async function main() {
    const rendered = renderTouLocaData(
        extractTouLocaData(await fs.readFile(SOURCE_PATH, 'utf8')),
    );
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/tou_loca_level_data.js is stale; run node scripts/generate-tou-loca-level.mjs');
    } else {
        await fs.writeFile(OUTPUT_PATH, rendered);
    }
}

if (process.argv[1] === SCRIPT_PATH) await main();
