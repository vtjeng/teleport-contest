#!/usr/bin/env node

// Generate the fixed map and monster descriptors for js/earth_levels.js
// from the authoritative nethack-c/upstream/dat/earth.lua program.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'earth.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'earth_level_data.js');

export function extractEarthMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('earth.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 20 || rows.some((row) => row.length !== 76)) {
        throw new SyntaxError('earth.lua map is not 20 rows of 76 columns');
    }
    return rows;
}

export function extractEarthMonsters(source) {
    const monsters = [];
    for (const line of source.split('\n')) {
        const call = line.match(/^\s*des\.monster\((.*)\)\s*$/u);
        if (!call) continue;
        const named = call[1].match(/^"([^"]+)",\s*(\d+),\s*(\d+)$/u);
        if (named) {
            monsters.push({
                form: 'named-at-coordinate',
                id: named[1],
                x: Number(named[2]),
                y: Number(named[3]),
            });
            continue;
        }
        const table = call[1].match(
            /^\{\s*id\s*=\s*"([^"]+)",\s*x\s*=\s*(\d+),\s*y\s*=\s*(\d+),\s*peaceful\s*=\s*0\s*\}$/u,
        );
        if (table) {
            monsters.push({
                form: 'table',
                id: table[1],
                x: Number(table[2]),
                y: Number(table[3]),
                peaceful: 0,
            });
            continue;
        }
        throw new SyntaxError(`unrecognized earth.lua monster call: ${line.trim()}`);
    }
    if (monsters.length !== 62) {
        throw new SyntaxError(`earth.lua has ${monsters.length} monster calls; expected 62`);
    }
    return monsters;
}

export function renderEarthData(rows, monsters) {
    return '// Generated by scripts/generate-earth-level.mjs from\n'
        + '// nethack-c/upstream/dat/earth.lua. Do not edit by hand.\n\n'
        + `export const EARTH_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n\n`
        + `export const EARTH_MONSTERS = Object.freeze(${JSON.stringify(monsters, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderEarthData(
        extractEarthMap(source),
        extractEarthMonsters(source),
    );
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/earth_level_data.js is stale; run '
                + 'node scripts/generate-earth-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
