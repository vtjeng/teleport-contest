#!/usr/bin/env node
// Generate dat/Sam-strt.lua's fixed geometry and placement descriptors.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Sam-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/sam_strt_level_data.js');

export function extractSamStrtData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\);/u);
    if (!map) throw new SyntaxError('Sam-strt.lua has no des.map block');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Sam-strt.lua map is not 20 rows of 76 columns');

    const doors = [...source.matchAll(/des\.door\("(locked|closed)",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, state, x, y]) => [state, Number(x), Number(y)]);
    const satoMatch = source.match(/des\.monster\(\{ id = "([^"]+)", coord = \{(\d+),\s*(\d+)\}, inventory = function\(\)\n([\s\S]*?)\nend \}\)/u);
    if (!satoMatch) throw new SyntaxError('Sam-strt.lua Lord Sato descriptor changed');
    const inventory = [...satoMatch[4].matchAll(/des\.object\(\{ id = "([^"]+)", spe = (-?\d+), eroded=(-?\d+), buc="([^"]+)" \}\)/gu)]
        .map(([, id, spe, eroded, buc]) => ({ id, spe: Number(spe), eroded: Number(eroded), buc }));
    const sato = { id: satoMatch[1], coord: [Number(satoMatch[2]), Number(satoMatch[3])] };
    const chestMatch = source.match(/des\.object\("([^"]+)",\s*(\d+),\s*(\d+)\)/u);
    if (!chestMatch) throw new SyntaxError('Sam-strt.lua floor chest descriptor changed');
    const chest = [chestMatch[1], Number(chestMatch[2]), Number(chestMatch[3])];

    const guards = [...source.matchAll(/^des\.monster\("roshi",\s*(\d+),\s*(\d+)\)$/gmu)]
        .map(([, x, y]) => ['roshi', Number(x), Number(y)]);
    const siegeText = source.slice(source.indexOf('-- Monsters on siege duty.'));
    if (siegeText === source) throw new SyntaxError('Sam-strt.lua siege section is missing');
    const siege = [...siegeText.matchAll(/^des\.monster\((.+)\)$/gmu)].map(([, args]) => {
        let match = args.match(/^\{ id = "([^"]+)", x=(\d+), y=(\d+), peaceful=0 \}$/u);
        if (match) return { id: match[1], x: Number(match[2]), y: Number(match[3]), peaceful: 0 };
        match = args.match(/^"([^"]+)"(?:,\s*(\d+),\s*(\d+))?$/u);
        if (!match) throw new SyntaxError(`Unexpected Sam-strt.lua siege monster: ${args}`);
        return match[2] === undefined
            ? [match[1]] : [match[1], Number(match[2]), Number(match[3])];
    });
    const traps = [...source.matchAll(/^des\.trap\(\)$/gmu)].length;
    if (doors.length !== 10 || inventory.length !== 2 || guards.length !== 8
        || siege.length !== 13 || traps !== 6)
        throw new SyntaxError('Sam-strt.lua descriptor counts changed');
    return { rows, doors, sato, inventory, chest, guards, siege, traps };
}

export function renderSamStrtData(data) {
    const tables = [
        ['MAP', data.rows], ['DOORS', data.doors], ['SATO', data.sato],
        ['SATO_INVENTORY', data.inventory], ['CHEST', data.chest],
        ['GUARDS', data.guards], ['SIEGE', data.siege],
    ];
    const rendered = tables.map(([name, values]) =>
        `export const SAM_STRT_LEVEL_${name} = Object.freeze(${JSON.stringify(values, null, 4)});\n`).join('\n');
    return '// Generated by scripts/generate-sam-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Sam-strt.lua. Do not edit by hand.\n\n'
        + rendered
        + `export const SAM_STRT_LEVEL_TRAP_COUNT = ${data.traps};\n`;
}

async function main() {
    const rendered = renderSamStrtData(extractSamStrtData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/sam_strt_level_data.js is stale; run node scripts/generate-sam-strt-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
