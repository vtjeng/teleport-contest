#!/usr/bin/env node

// Generate the fixed map rows used by js/quest_levels.js from
// dat/Sam-goal.lua, so the JavaScript map stays tied to its Lua source.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Sam-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'sam_goal_level_data.js');

export function extractSamGoalMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('Sam-goal.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 20 || rows.some((row) => row.length !== 45)) {
        throw new SyntaxError('Sam-goal.lua map is not 20 rows of 45 columns');
    }
    return rows;
}

export function renderSamGoalMap(rows) {
    return '// Generated by scripts/generate-sam-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Sam-goal.lua. Do not edit by hand.\n\n'
        + `export const SAM_GOAL_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderSamGoalMap(extractSamGoalMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/sam_goal_level_data.js is stale; run '
                + 'node scripts/generate-sam-goal-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
