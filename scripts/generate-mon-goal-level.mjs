#!/usr/bin/env node

// Generate the fixed map rows used by js/quest_levels.js from
// dat/Mon-goal.lua, so the JavaScript map stays tied to its Lua source.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Mon-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'mon_goal_level_data.js');

export function extractMonGoalMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('Mon-goal.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 11 || rows.some((row) => row.length !== 26)) {
        throw new SyntaxError('Mon-goal.lua map is not 11 rows of 26 columns');
    }
    return rows;
}

export function renderMonGoalMap(rows) {
    return '// Generated by scripts/generate-mon-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Mon-goal.lua. Do not edit by hand.\n\n'
        + `export const MON_GOAL_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderMonGoalMap(extractMonGoalMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/mon_goal_level_data.js is stale; run '
                + 'node scripts/generate-mon-goal-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
