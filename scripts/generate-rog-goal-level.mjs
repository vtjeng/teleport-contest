#!/usr/bin/env node
// Generate Rog-goal's exact cave map and ordered monster table from Lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
export function extractRogGoalData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u)?.[1].split('\n');
    // Lua12–32: full 76-column, 21-row fragment including all trailing spaces.
    if (!map || map.length !== 21 || map.some(row => row.length !== 76))
        throw new SyntaxError('Rog-goal map dimensions changed');
    const monsters = [...source.matchAll(/^des\.monster\(\{([^\n]*)\}\)$/gmu)].map(([, body]) => {
        const descriptor = {};
        const fieldPattern = /([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu;
        const residue = body.replace(fieldPattern, '').replace(/[\s,]/gu, '');
        if (residue) throw new SyntaxError(`Unsupported Rog-goal descriptor: ${body}`);
        for (const [, key, token] of body.matchAll(fieldPattern)) {
            if (!['id', 'class', 'x', 'y', 'peaceful'].includes(key))
                throw new SyntaxError(`Unsupported monster field: ${key}`);
            descriptor[key] = token.startsWith('"') ? JSON.parse(token) : Number(token);
        }
        return descriptor;
    });
    // Lua72–110: leader,16 leprechauns,2class l,8nagas,3class N,5chameleons,4sharks.
    if (monsters.length !== 39) throw new SyntaxError('Rog-goal monster count changed');
    return { map, monsters };
}
export function renderRogGoalData(data) {
    return '// Generated by scripts/generate-rog-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Rog-goal.lua. Do not edit by hand.\n\n'
        + `export const ROG_GOAL_LEVEL_MAP = Object.freeze(${JSON.stringify(data.map, null, 4)});\n\n`
        + `export const ROG_GOAL_MONSTERS = Object.freeze(${JSON.stringify(data.monsters, null, 4)});\n`;
}
async function main() {
    const output = path.join(ROOT, 'js/rog_goal_level_data.js');
    const rendered = renderRogGoalData(extractRogGoalData(await fs.readFile(
        path.join(ROOT, 'nethack-c/upstream/dat/Rog-goal.lua'), 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(output, 'utf8') !== rendered) throw new Error('rog_goal_level_data.js is stale');
    } else await fs.writeFile(output, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
