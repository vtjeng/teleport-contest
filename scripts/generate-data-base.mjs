#!/usr/bin/env node

// Project NetHack's encyclopedia source into browser-safe lookup records.
// pager.c checkfile() needs both the ordered key groups and their text; the
// game cannot open dat/data.base at runtime.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'dat', 'data.base');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'data_base_data.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';
const BUFSZ = 256;

function expandTabs(value) {
    let result = '';
    let column = 0;
    for (const character of value) {
        if (character === '\t') {
            do {
                result += ' ';
                column += 1;
            } while (column % 8);
        } else {
            result += character;
            column += 1;
        }
        // hacklib.c tabexpand() reserves the last byte for the terminator.
        if (column >= BUFSZ) return result.slice(0, BUFSZ - 1);
    }
    return result;
}

function displayLine(sourceLine) {
    let line = sourceLine;
    if (line.startsWith('\t')) {
        line = line.slice(1);
    } else if (line.startsWith(' ')) {
        // pager.c checkfile() accepts source edits made with spaces and strips
        // at most one eight-column indentation level.
        let count = 0;
        while (count < 8 && line[count] === ' ') count += 1;
        line = line.slice(count);
    } else if (line) {
        throw new Error('data.base description line has no indentation');
    }
    return line.includes('\t') ? expandTabs(line) : line;
}

export function parseDataBase(source) {
    if (source.includes('\r'))
        throw new Error('data.base contains a carriage return');

    const entries = [];
    let keys = [];
    let lines = [];
    let readingText = false;

    const finishEntry = () => {
        if (!keys.length) return;
        if (!readingText)
            throw new Error(`data.base keys have no description: ${keys[0]}`);
        entries.push({ keys, lines });
        keys = [];
        lines = [];
        readingText = false;
    };

    const sourceLines = (source.endsWith('\n') ? source.slice(0, -1) : source)
        .split('\n');
    for (const line of sourceLines) {
        if (line.startsWith('#')) continue;
        if (line === '' || /^[\t ]/u.test(line)) {
            if (readingText) {
                lines.push(displayLine(line));
            } else if (line !== '') {
                if (!keys.length)
                    throw new Error('data.base starts text without a key');
                readingText = true;
                lines.push(displayLine(line));
            }
            continue;
        }
        if (readingText) finishEntry();
        keys.push(line);
    }
    finishEntry();
    return entries;
}

export function renderDataBaseData(entries) {
    return '// Generated by scripts/generate-data-base.mjs.\n'
        + `// Source: NetHack 5.0 dat/data.base at ${PINNED_REVISION}.\n`
        + '// Do not edit this file by hand.\n\n'
        + 'export const DATA_BASE_ENTRIES = Object.freeze('
        + `${JSON.stringify(entries, null, 4)}\n` + '.map((entry) => Object.freeze({\n'
        + '    keys: Object.freeze(entry.keys),\n'
        + '    lines: Object.freeze(entry.lines),\n'
        + '})));\n';
}

function assertPinnedSource() {
    const revision = execFileSync(
        'git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], { encoding: 'utf8' },
    ).trim();
    if (revision !== PINNED_REVISION) {
        throw new Error(
            `expected NetHack source ${PINNED_REVISION}; found ${revision}`,
        );
    }
    const status = execFileSync(
        'git', [
            '-C', UPSTREAM_ROOT, 'status', '--porcelain=v1',
            '--untracked-files=no',
        ],
        { encoding: 'utf8' },
    ).trim();
    if (status)
        throw new Error('refusing to generate from modified upstream sources');
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-data-base.mjs [--check]');

    assertPinnedSource();
    const output = renderDataBaseData(parseDataBase(
        readFileSync(SOURCE_PATH, 'utf8'),
    ));
    if (checkOnly) {
        let existing = '';
        try {
            existing = readFileSync(OUTPUT_PATH, 'utf8');
        } catch {
            // The comparison below reports the missing generated file.
        }
        if (existing !== output) {
            console.error(
                'js/data_base_data.js is stale; run '
                + 'node scripts/generate-data-base.mjs',
            );
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1]
    && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
