#!/usr/bin/env node

// Generate Val-goal's fixed map and ordered Lua descriptors from source.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Val-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'val_goal_level_data.js');

function luaValue(token) {
    if (token.startsWith('"')) return JSON.parse(token);
    const number = Number(token);
    if (!Number.isInteger(number)) throw new SyntaxError(`Unsupported Lua value: ${token}`);
    return number;
}

function descriptor(body, allowed) {
    const values = {};
    const fields = [...body.matchAll(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu)];
    const residue = body.replace(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu, '')
        .replace(/[\s,]/gu, '');
    if (!fields.length || residue) throw new SyntaxError(`Unsupported descriptor: {${body}}`);
    for (const [, key, value] of fields) {
        if (!allowed.includes(key)) throw new SyntaxError(`Unsupported descriptor field: ${key}`);
        values[key] = luaValue(value);
    }
    return values;
}

function calls(source, name, allowed) {
    const result = [];
    for (const line of source.split('\n')) {
        const match = line.match(new RegExp(`^des\\.${name}\\((.*)\\)$`, 'u'));
        if (!match) continue;
        const body = match[1];
        if (!body) result.push([]);
        else if (body.startsWith('{')) result.push([descriptor(body.slice(1, -1), allowed)]);
        else {
            const args = [...body.matchAll(/"([^"]*)"|(-?\d+)/gu)];
            if (!args.length || body.replace(/"[^"]*"|-?\d+/gu, '').replace(/[\s,]/gu, ''))
                throw new SyntaxError(`Unsupported ${name} call: ${body}`);
            result.push(args.map(([, string, number]) => string === undefined ? Number(number) : string));
        }
    }
    return result;
}

export function extractValGoalData(source) {
    const mapMatch = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\);/u);
    if (!mapMatch) throw new SyntaxError('Val-goal.lua has no literal des.map block');
    const map = mapMatch[1].split('\n');
    if (map.length !== 17 || map.some(row => row.length !== 35))
        throw new SyntaxError('Val-goal.lua map is not 17 rows of 35 columns');
    const objects = calls(source, 'object', ['id', 'x', 'y', 'buc', 'spe', 'name']);
    const traps = calls(source, 'trap', []);
    const monsters = calls(source, 'monster', ['id', 'class', 'x', 'y', 'peaceful']);
    if (objects.length !== 15) throw new SyntaxError(`Expected 15 objects, got ${objects.length}`);
    if (traps.length !== 9) throw new SyntaxError(`Expected 9 traps, got ${traps.length}`);
    if (monsters.length !== 20) throw new SyntaxError(`Expected 20 monsters, got ${monsters.length}`);
    const bridges = [...source.matchAll(/^\s*des\.drawbridge\(\{([^\n]*)\}\)$/gmu)]
        .map(([, body]) => descriptor(body, ['x', 'y', 'dir', 'state']));
    if (bridges.length !== 3) throw new SyntaxError(`Expected 3 bridge call descriptors, got ${bridges.length}`);
    if (!source.includes('if percent(75) then')) throw new SyntaxError('Missing 75 percent bridge branch');
    return { map, objects, traps, monsters, bridges };
}

export function renderValGoalData(data) {
    return '// Generated by scripts/generate-val-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Val-goal.lua. Do not edit by hand.\n\n'
        + `export const VAL_GOAL_LEVEL_MAP = Object.freeze(${JSON.stringify(data.map, null, 4)});\n\n`
        + `export const VAL_GOAL_OBJECT_CALLS = Object.freeze(${JSON.stringify(data.objects, null, 4)});\n\n`
        + `export const VAL_GOAL_TRAPS = Object.freeze(${JSON.stringify(data.traps, null, 4)});\n\n`
        + `export const VAL_GOAL_MONSTERS = Object.freeze(${JSON.stringify(data.monsters, null, 4)});\n\n`
        + `export const VAL_GOAL_DRAWBRIDGES = Object.freeze(${JSON.stringify(data.bridges, null, 4)});\n`;
}

async function main() {
    const rendered = renderValGoalData(extractValGoalData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) throw new Error('js/val_goal_level_data.js is stale; run node scripts/generate-val-goal-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
