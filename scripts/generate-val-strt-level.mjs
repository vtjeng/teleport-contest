#!/usr/bin/env node
// Generate Val-strt's fixed map directly from the upstream Lua program.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Val-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/val_strt_level_data.js');

export function extractValStrtData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Val-strt.lua has no des.map block');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Val-strt.lua map is not 20 rows of 76 columns');
    return { rows };
}

export function renderValStrtData(data) {
    return '// Generated by scripts/generate-val-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Val-strt.lua. Do not edit by hand.\n\n'
        + `export const VAL_STRT_LEVEL_MAP = Object.freeze(${JSON.stringify(data.rows, null, 4)});\n`;
}

async function main() {
    const output = renderValStrtData(
        extractValStrtData(await fs.readFile(SOURCE_PATH, 'utf8')),
    );
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== output)
            throw new Error('js/val_strt_level_data.js is stale; run node scripts/generate-val-strt-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, output);
}

if (process.argv[1] === SCRIPT_PATH) await main();
