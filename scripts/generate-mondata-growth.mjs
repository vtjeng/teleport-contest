#!/usr/bin/env node

// Generate the mondata.c grownups[] progression table inside mondata.js.
// The active source order controls both conversion directions, including the
// first-child choice when several young forms share one adult form.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const UPSTREAM_ROOT = join(PROJECT_ROOT, 'nethack-c', 'upstream');
const SOURCE_PATH = join(UPSTREAM_ROOT, 'src', 'mondata.c');
const OUTPUT_PATH = join(PROJECT_ROOT, 'js', 'mondata.js');
const PINNED_REVISION = '16ff59115315917b93185d026aeefea06db9b0f4';
export const GROWTH_START_MARKER = '// BEGIN GENERATED mondata.c grownups[]';
export const GROWTH_END_MARKER = '// END GENERATED mondata.c grownups[]';

export function parseGrowthRows(source) {
    const declaration = source.indexOf('static const short grownups[][2]');
    const open = source.indexOf('{', declaration);
    const close = source.indexOf('\n};', open);
    if (declaration < 0 || open < 0 || close < 0)
        throw new Error('mondata.c grownups[] definition not found');

    const body = source.slice(open + 1, close)
        .replace(/#if\s+0\b[\s\S]*?#endif/g, '')
        .replace(/\/\*[\s\S]*?\*\//g, '');
    const pairPattern = /\{\s*(NON_PM|PM_[A-Z0-9_]+)\s*,\s*(NON_PM|PM_[A-Z0-9_]+)\s*\}/g;
    const rows = [...body.matchAll(pairPattern)]
        .map((match) => [match[1], match[2]]);
    const remainder = body.replace(pairPattern, '').replace(/[\s{},;]/g, '');
    if (remainder)
        throw new Error(`unparsed mondata.c grownups[] syntax: ${remainder}`);
    if (rows.length !== 68 || rows.at(-1)?.[0] !== 'NON_PM'
        || rows.at(-1)?.[1] !== 'NON_PM'
        || rows.slice(0, -1).some(([little, big]) =>
            little === 'NON_PM' || big === 'NON_PM')) {
        throw new Error('grownups[] must contain 67 active rows and one NON_PM terminator');
    }
    return rows;
}

export function renderGrowthTable(rows) {
    if (rows.length !== 68 || rows.at(-1)?.[0] !== 'NON_PM'
        || rows.at(-1)?.[1] !== 'NON_PM') {
        throw new Error('renderGrowthTable requires the active rows and C sentinel');
    }
    const activeRows = rows.slice(0, -1)
        .map(([little, big]) => `    pair(M.${little}, M.${big}),`)
        .join('\n');
    return [
        GROWTH_START_MARKER,
        '// Generated by scripts/generate-mondata-growth.mjs from mondata.c.',
        'const grownups = Object.freeze([',
        activeRows,
        ']);',
        GROWTH_END_MARKER,
    ].join('\n');
}

function sourceRevision() {
    return execFileSync('git', ['-C', UPSTREAM_ROOT, 'rev-parse', 'HEAD'], {
        encoding: 'utf8',
    }).trim();
}

function sourceStatus() {
    return execFileSync('git', [
        '-C', UPSTREAM_ROOT, 'status', '--porcelain=v1', '--untracked-files=no',
    ], { encoding: 'utf8' }).trim();
}

export function generatedMondataSource(cSource, jsSource) {
    const rendered = renderGrowthTable(parseGrowthRows(cSource));
    const start = jsSource.indexOf(GROWTH_START_MARKER);
    const end = jsSource.indexOf(GROWTH_END_MARKER, start + GROWTH_START_MARKER.length);
    if (start < 0 || end < 0)
        throw new Error('mondata.js generated grownups[] markers are missing');
    return jsSource.slice(0, start) + rendered
        + jsSource.slice(end + GROWTH_END_MARKER.length);
}

function main() {
    const checkOnly = process.argv.length === 3 && process.argv[2] === '--check';
    if (process.argv.length > (checkOnly ? 3 : 2))
        throw new Error('Usage: node scripts/generate-mondata-growth.mjs [--check]');
    if (sourceRevision() !== PINNED_REVISION)
        throw new Error(`expected NetHack source ${PINNED_REVISION}; found ${sourceRevision()}`);
    if (sourceStatus())
        throw new Error('refusing to generate from modified upstream sources');

    const cSource = readFileSync(SOURCE_PATH, 'utf8');
    const jsSource = readFileSync(OUTPUT_PATH, 'utf8');
    const output = generatedMondataSource(cSource, jsSource);
    if (checkOnly) {
        if (jsSource !== output) {
            console.error('js/mondata.js grownups[] is stale; run node scripts/generate-mondata-growth.mjs');
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUTPUT_PATH, output);
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
    main();
