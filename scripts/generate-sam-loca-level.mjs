#!/usr/bin/env node
// Generate the fixed map and descriptor tables from the whole Sam-loca program.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Sam-loca.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/sam_loca_level_data.js');

export function extractSamLocaData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Sam-loca.lua has no des.map block');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Sam-loca.lua map is not 20 rows of 76 columns');
    const doors = [...source.matchAll(/des\.door\("(locked|closed)",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, state, x, y]) => [state, Number(x), Number(y)]);
    const objects = [...source.matchAll(/des\.object\("([*\[)(])",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, type, x, y]) => [type, Number(x), Number(y)]);
    const monsters = [...source.matchAll(/^des\.monster\((.+)\)$/gmu)].map(([, args]) => {
        if (args.startsWith('{')) {
            const match = args.match(/^\{ id = "([^"]+)", x=(\d+), y=(\d+), peaceful=0 \}$/u);
            if (!match) throw new SyntaxError(`Unexpected Sam-loca monster: ${args}`);
            return [{ id: match[1], x: Number(match[2]), y: Number(match[3]), peaceful: 0 }];
        }
        const match = args.match(/^"([^"]+)"(?:,\s*(\d+),\s*(\d+))?$/u);
        if (!match) throw new SyntaxError(`Unexpected Sam-loca monster: ${args}`);
        return match[2] === undefined ? [match[1]] : [match[1], Number(match[2]), Number(match[3])];
    });
    if (doors.length !== 24 || objects.length !== 32 || monsters.length !== 33)
        throw new SyntaxError('Sam-loca.lua descriptor counts changed');
    return { rows, doors, objects, monsters };
}
export function renderSamLocaData(data) {
    const tables = [['MAP', data.rows], ['DOORS', data.doors],
        ['OBJECTS', data.objects], ['MONSTERS', data.monsters]];
    return '// Generated by scripts/generate-sam-loca-level.mjs from\n'
        + '// nethack-c/upstream/dat/Sam-loca.lua. Do not edit by hand.\n\n'
        + tables.map(([name, values]) => `export const SAM_LOCA_LEVEL_${name} = Object.freeze(${JSON.stringify(values, null, 4)});\n`).join('\n');
}
async function main() {
    const output = renderSamLocaData(extractSamLocaData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== output)
            throw new Error('js/sam_loca_level_data.js is stale; run node scripts/generate-sam-loca-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, output);
}
if (process.argv[1] === SCRIPT_PATH) await main();
