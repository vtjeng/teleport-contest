#!/usr/bin/env node

// Generate Kni-loca's fixed map, trap coordinates, and monster descriptors
// from the authoritative Lua program.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Kni-loca.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'kni_loca_level_data.js');

export function extractKniLocaData(source) {
    const mapMatch = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!mapMatch) throw new SyntaxError('Kni-loca.lua has no des.map block');
    const map = mapMatch[1].split('\n');
    if (map.length !== 12 || map.some(row => row.length !== 40)) {
        throw new SyntaxError('Kni-loca.lua map is not 12 rows of 40 columns');
    }

    const fixedTraps = [...source.matchAll(
        /^des\.trap\("([^"]+)",\s*(\d+),\s*(\d+)\)$/gmu,
    )].map(([, type, x, y]) => ({ type, x: Number(x), y: Number(y) }));
    if (fixedTraps.length !== 45) {
        throw new SyntaxError('Kni-loca.lua does not have 45 fixed traps');
    }

    const monsters = [...source.matchAll(
        /^des\.monster\(\{\s*(id|class)\s*=\s*"([^"]+)"\s*,\s*peaceful\s*=\s*0\s*\}\)$/gmu,
    )].map(([, field, value]) => ({ [field]: value, peaceful: 0 }));
    if (monsters.length !== 27) {
        throw new SyntaxError('Kni-loca.lua does not have 27 explicit monster descriptors');
    }
    return { map, fixedTraps, monsters };
}

export function renderKniLocaData({ map, fixedTraps, monsters }) {
    return '// Generated by scripts/generate-kni-loca-level.mjs from\n'
        + '// nethack-c/upstream/dat/Kni-loca.lua. Do not edit by hand.\n\n'
        + `export const KNI_LOCA_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const KNI_LOCA_FIXED_TRAPS = Object.freeze(${JSON.stringify(fixedTraps, null, 4)});\n\n`
        + `export const KNI_LOCA_MONSTERS = Object.freeze(${JSON.stringify(monsters, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderKniLocaData(extractKniLocaData(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/kni_loca_level_data.js is stale; run '
                + 'node scripts/generate-kni-loca-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
