#!/usr/bin/env node
// Generate Fort Ludios's fixed map directly from dat/knox.lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/knox.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/knox_level_data.js');

export function extractKnoxLevelMap(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('knox.lua has no des.map block');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('knox.lua map is not 20 rows of 76 columns');
    return rows;
}

export function renderKnoxLevelMap(rows) {
    return '// Generated by scripts/generate-knox-level.mjs from\n'
        + '// nethack-c/upstream/dat/knox.lua. Do not edit by hand.\n\n'
        + `export const KNOX_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const output = renderKnoxLevelMap(
        extractKnoxLevelMap(await fs.readFile(SOURCE_PATH, 'utf8')),
    );
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== output)
            throw new Error('js/knox_level_data.js is stale; run node scripts/generate-knox-level.mjs');
    } else {
        await fs.writeFile(OUTPUT_PATH, output);
    }
}

if (process.argv[1] === SCRIPT_PATH) await main();
