#!/usr/bin/env node

// Generate the fixed map rows used by js/fire_levels.js from dat/fire.lua.
// The level loader remains source-shaped, while this check keeps the copied
// table tied to the authoritative Lua level definition.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'fire.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'fire_level_data.js');

export function extractFireMap(source) {
    const match = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!match) throw new SyntaxError('fire.lua has no des.map block');
    const rows = match[1].split('\n');
    if (rows.length !== 21 || rows.some((row) => row.length !== 79)) {
        throw new SyntaxError('fire.lua map is not 21 rows of 79 columns');
    }
    return rows;
}

export function renderFireMap(rows) {
    return '// Generated by scripts/generate-fire-level.mjs from\n'
        + '// nethack-c/upstream/dat/fire.lua. Do not edit by hand.\n\n'
        + `export const FIRE_LEVEL_MAP = Object.freeze(${JSON.stringify(rows, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderFireMap(extractFireMap(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error(
                'js/fire_level_data.js is stale; run '
                + 'node scripts/generate-fire-level.mjs',
            );
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
