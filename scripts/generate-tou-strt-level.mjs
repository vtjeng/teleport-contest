#!/usr/bin/env node
// Generate the Tourist start map and fixed placement tables from Lua.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c/upstream/dat/Tou-strt.lua');
const OUTPUT_PATH = path.join(ROOT, 'js/tou_strt_level_data.js');
export function extractTouStrtData(source) {
    const map = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\)/u);
    if (!map) throw new SyntaxError('Tou-strt.lua has no map');
    const rows = map[1].split('\n');
    if (rows.length !== 20 || rows.some(row => row.length !== 76))
        throw new SyntaxError('Tou-strt.lua map dimensions changed');
    const doors = [...source.matchAll(/des\.door\("(\w+)",(\d+),(\d+)\)/gu)]
        .map(([, state, x, y]) => [state, Number(x), Number(y)]);
    const guides = [...source.matchAll(/des\.monster\("guide",\s*(\d+),\s*(\d+)\)/gu)]
        .map(([, x, y]) => [Number(x), Number(y)]);
    return { rows, doors, guides };
}
export function renderTouStrtData({ rows, doors, guides }) {
    return '// Generated by scripts/generate-tou-strt-level.mjs from\n'
        + '// nethack-c/upstream/dat/Tou-strt.lua. Do not edit by hand.\n\n'
        + [['TOU_STRT_LEVEL_MAP', rows], ['TOU_STRT_DOORS', doors], ['TOU_STRT_GUIDES', guides]]
            .map(([name, data]) => `export const ${name} = Object.freeze(${JSON.stringify(data, null, 4)});\n`)
            .join('\n');
}
async function main() {
    const rendered = renderTouStrtData(extractTouStrtData(await fs.readFile(SOURCE_PATH, 'utf8')));
    if (process.argv.includes('--check')) {
        if (await fs.readFile(OUTPUT_PATH, 'utf8') !== rendered)
            throw new Error('js/tou_strt_level_data.js is stale; run node scripts/generate-tou-strt-level.mjs');
    } else await fs.writeFile(OUTPUT_PATH, rendered);
}
if (process.argv[1] === SCRIPT_PATH) await main();
