#!/usr/bin/env node

// Generate Ran-goal's fixed map and ordered descriptors from the source Lua.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.dirname(path.dirname(SCRIPT_PATH));
const SOURCE_PATH = path.join(ROOT, 'nethack-c', 'upstream', 'dat', 'Ran-goal.lua');
const OUTPUT_PATH = path.join(ROOT, 'js', 'ran_goal_level_data.js');

function luaScalar(token) {
    if (token.startsWith('"')) return JSON.parse(token);
    const number = Number(token);
    if (!Number.isInteger(number)) throw new SyntaxError(`Unsupported Lua value: ${token}`);
    return number;
}

function descriptors(source, name, fieldsAllowed) {
    return [...source.matchAll(new RegExp(`^des\\.${name}\\(\\{([^\\n]*)\\}\\)$`, 'gmu'))]
        .map(([, body]) => {
            const descriptor = {};
            const fields = [...body.matchAll(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu)];
            const residue = body.replace(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu, '')
                .replace(/[\s,]/gu, '');
            if (!fields.length || residue) {
                throw new SyntaxError(`Unsupported ${name} descriptor: {${body}}`);
            }
            for (const [, key, token] of fields) {
                if (!fieldsAllowed.includes(key)) {
                    throw new SyntaxError(`Unsupported ${name} field: ${key}`);
                }
                descriptor[key] = luaScalar(token);
            }
            return descriptor;
        });
}

function objectCalls(source) {
    const calls = [];
    for (const line of source.split('\n')) {
        const match = line.match(/^des\.object\((.*)\)$/u);
        if (!match) continue;
        const body = match[1];
        if (!body) {
            calls.push([]);
        } else if (body.startsWith('{ coord = {')) {
            const coord = body.match(/^\{ coord = \{\s*(\d+)\s*,\s*(\d+)\s*\} \}$/u);
            if (!coord) throw new SyntaxError(`Unsupported object coordinate: ${body}`);
            calls.push([{ coord: [Number(coord[1]), Number(coord[2])] }]);
        } else if (body.startsWith('{ ')) {
            const descriptor = {};
            const fields = [...body.slice(1, -1).matchAll(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu)];
            const residue = body.slice(1, -1)
                .replace(/([a-z]+)\s*=\s*("[^"]*"|-?\d+)/gu, '')
                .replace(/[\s,]/gu, '');
            if (!fields.length || residue) throw new SyntaxError(`Unsupported object descriptor: ${body}`);
            for (const [, key, token] of fields) {
                if (!['id', 'x', 'y', 'buc', 'spe', 'name'].includes(key)) {
                    throw new SyntaxError(`Unsupported object field: ${key}`);
                }
                descriptor[key] = luaScalar(token);
            }
            calls.push([descriptor]);
        } else {
            const matchArgs = body.match(/^"([^"]+)"\s*,\s*(\d+)\s*,\s*(\d+)$/u);
            if (!matchArgs) throw new SyntaxError(`Unsupported positional object call: ${body}`);
            calls.push([matchArgs[1], Number(matchArgs[2]), Number(matchArgs[3])]);
        }
    }
    return calls;
}

export function extractRanGoalData(source) {
    const mapMatch = source.match(/des\.map\(\[\[\n([\s\S]*?)\n\]\]\);/u);
    if (!mapMatch) throw new SyntaxError('Ran-goal.lua has no literal des.map block');
    const map = mapMatch[1].split('\n');
    if (map.length !== 20 || map.some(row => row.length !== 76)) {
        throw new SyntaxError('Ran-goal.lua map is not 20 rows of 76 columns');
    }

    const objects = objectCalls(source);
    if (objects.length !== 15) throw new SyntaxError(`Ran-goal.lua has ${objects.length}, expected 15 object calls`);

    const traps = [...source.matchAll(/^des\.trap\(\)$/gmu)].length;
    if (traps !== 6) throw new SyntaxError(`Ran-goal.lua has ${traps}, expected 6 random traps`);

    const doors = [...source.matchAll(/^des\.door\("([^"]+)",\s*(\d+),\s*(\d+)\)$/gmu)]
        .map(([, type, x, y]) => ({ type, x: Number(x), y: Number(y) }));
    if (doors.length !== 14) throw new SyntaxError(`Ran-goal.lua has ${doors.length}, expected 14 doors`);

    const monsters = descriptors(source, 'monster', ['id', 'class', 'x', 'y', 'peaceful']);
    if (monsters.length !== 28) {
        throw new SyntaxError(`Ran-goal.lua has ${monsters.length}, expected 28 monster descriptors`);
    }
    return { map, objects, trapCount: traps, doors, monsters };
}

export function renderRanGoalData({ map, objects, trapCount, doors, monsters }) {
    return '// Generated by scripts/generate-ran-goal-level.mjs from\n'
        + '// nethack-c/upstream/dat/Ran-goal.lua. Do not edit by hand.\n\n'
        + `export const RAN_GOAL_LEVEL_MAP = Object.freeze(${JSON.stringify(map, null, 4)});\n\n`
        + `export const RAN_GOAL_OBJECT_CALLS = Object.freeze(${JSON.stringify(objects, null, 4)});\n\n`
        + `export const RAN_GOAL_TRAP_COUNT = ${trapCount};\n\n`
        + `export const RAN_GOAL_DOORS = Object.freeze(${JSON.stringify(doors, null, 4)});\n\n`
        + `export const RAN_GOAL_MONSTERS = Object.freeze(${JSON.stringify(monsters, null, 4)});\n`;
}

async function main() {
    const source = await fs.readFile(SOURCE_PATH, 'utf8');
    const rendered = renderRanGoalData(extractRanGoalData(source));
    if (process.argv.includes('--check')) {
        const current = await fs.readFile(OUTPUT_PATH, 'utf8');
        if (current !== rendered) {
            throw new Error('js/ran_goal_level_data.js is stale; run node scripts/generate-ran-goal-level.mjs');
        }
        return;
    }
    await fs.writeFile(OUTPUT_PATH, rendered);
}

if (process.argv[1] === SCRIPT_PATH) await main();
